-- 프로모션 코드(`/admin/promotions`) — 저장하고, 바코드로 찍어 티 시트 계산서에서 할인한다.
--
-- 왜(2026-10-22): Promotions 화면은 화면 안의 예시였다(새로고침하면 사라지고, 예약에 적용할 곳이 없었다).
-- 클럽이 "바코드를 만들어 우리가 찍으면 티 시트에 반영돼 쓸 수 있게" 해 달라고 했다.
--
-- 흐름:
--   1. 직원이 Promotions 에서 코드를 만든다(FALL18). 바코드 값은 `PROMO-` + 코드(PROMO-FALL18).
--   2. 마케팅 문자(0047)에 그 바코드 그림이 MMS 로 붙어 나간다(백엔드 marketing.py).
--   3. 손님이 휴대폰 화면을 내밀면, 티 시트에서 그린피를 계산서에 담은 뒤 바코드를 찍는다.
--      코드만 말하면 계산서의 "Promo code" 칸에 FALL18 을 쳐도 된다.
--   4. 서버가 할인 금액을 계산해 계산서 할인(pelham_bills.discount)에 더하고, 어떤 코드였는지 남긴다.
--
-- 할인 계산(그린피 줄 = kind 'tee_player' 인 활성 줄만 본다 — 상품·음료에는 안 붙는다):
--   amount + per_player  value(센트) × 그린피 인원
--   amount               value(센트) 한 번(계산서당)
--   percent              그린피 합계 × value%
--   어느 쪽이든 그린피 합계를 넘지 않는다. 계산서 하나에 코드 하나.
--   찍은 뒤 사람을 더 담았으면 코드를 지우고 다시 찍는다(금액은 찍는 순간 정해진다).
--
-- 사용 횟수: 결제된 계산서(paid)만 센다. 환불(refunded)·취소(void)된 계산서는 빠진다.
--   한도 판정에는 아직 결제 안 된 열린 계산서도 넣는다(두 계산대가 마지막 한 장을 같이 쓰지 않게).
-- 조건(conditions)은 안내 문구다 — "Mon-Thu, 18 holes" 같은 것은 직원이 눈으로 확인한다.
--
-- 함수: pelham_staff_promotions, pelham_staff_promotion_save, pelham_staff_promotion,
--       pelham_staff_bill_apply_promo, pelham_staff_bill_remove_promo, pelham_staff_bill_promo
--
-- 전제: 0004, 0005. 실행: SQL editor 에 이 파일 전체를 붙여 한 번. 다시 실행해도 안전하다.

do $$
begin
  if to_regprocedure('public.pelham_require_staff()') is null then
    raise exception '0078 needs 0004 first (pelham_require_staff is missing).';
  end if;
  if to_regprocedure('public.pelham_pos_recalc(bigint)') is null then
    raise exception '0078 needs 0005 first (pelham_pos_recalc is missing).';
  end if;
end;
$$;

-- ===== 테이블 ==========================================================

create table if not exists public.pelham_promotions (
  id            bigint generated by default as identity primary key,
  code          text not null unique check (code ~ '^[A-Z0-9]{3,16}$'),
  name          text not null check (btrim(name) <> ''),
  kind          text not null check (kind in ('amount', 'percent')),
  value         integer not null check (value > 0),
  per_player    boolean not null default true,
  conditions    text,
  starts_on     date,
  expires_on    date,
  usage_limit   integer check (usage_limit is null or usage_limit > 0),
  active        boolean not null default true,
  created_by    text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  check (kind <> 'percent' or value <= 100),
  check (starts_on is null or expires_on is null or starts_on <= expires_on)
);

-- 계산서 하나에 코드 하나. amount 는 그 계산서 할인에 더한 센트.
create table if not exists public.pelham_promo_uses (
  bill_id       bigint primary key references public.pelham_bills (id) on delete cascade,
  promo_id      bigint not null references public.pelham_promotions (id),
  amount        integer not null check (amount >= 0),
  applied_by    text,
  applied_at    timestamptz not null default now()
);

create index if not exists pelham_promo_uses_promo_idx on public.pelham_promo_uses (promo_id);

alter table public.pelham_promotions enable row level security;
alter table public.pelham_promo_uses enable row level security;
revoke all on public.pelham_promotions from anon, authenticated;
revoke all on public.pelham_promo_uses from anon, authenticated;

-- ===== 도우미 ==========================================================

-- 'PROMO-FALL18', 'promo-fall18', ' FALL18 ' → 'FALL18'
create or replace function public.pelham_promo_code(p_raw text)
returns text
language sql
immutable
set search_path = ''
as $$
  select regexp_replace(upper(btrim(coalesce(p_raw, ''))), '^PROMO-', '')
$$;

-- 결제된 계산서 수(used)와, 아직 열린 계산서에 걸린 수(held).
create or replace function public.pelham_promo_json(p_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select to_jsonb(p)
         || jsonb_build_object(
              'barcode', 'PROMO-' || p.code,
              'used', u.used,
              'held', u.held,
              'state', case
                when not p.active then 'paused'
                when p.expires_on is not null and p.expires_on < public.pelham_pos_today() then 'expired'
                when p.starts_on is not null and p.starts_on > public.pelham_pos_today() then 'scheduled'
                when p.usage_limit is not null and u.used >= p.usage_limit then 'used_up'
                else 'active'
              end)
    from public.pelham_promotions p
    cross join lateral (
      select count(*) filter (where b.status = 'paid') as used,
             count(*) filter (where b.status = 'open') as held
        from public.pelham_promo_uses x
        join public.pelham_bills b on b.id = x.bill_id
       where x.promo_id = p.id
    ) u
   where p.id = p_id
$$;

-- ===== 프로모션 목록·저장 ================================================

create or replace function public.pelham_staff_promotions()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_staff();
  return coalesce((
    select jsonb_agg(public.pelham_promo_json(p.id) order by p.active desc, p.created_at desc)
      from public.pelham_promotions p
  ), '[]'::jsonb);
end;
$$;

-- p: {id?, code, name, kind: amount|percent, value, per_player?, conditions?, starts_on?, expires_on?,
--     usage_limit?, active?}. id 가 있으면 고친다(코드는 바꾸지 않는다 — 이미 나간 바코드가 있다).
create or replace function public.pelham_staff_promotion_save(p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_id bigint := nullif(p->>'id', '')::bigint;
  v_code text := public.pelham_promo_code(p->>'code');
  v_name text := btrim(coalesce(p->>'name', ''));
  v_kind text := coalesce(p->>'kind', 'amount');
  v_value integer := nullif(p->>'value', '')::integer;
  v_by text;
begin
  perform public.pelham_require_staff();
  if v_name = '' then
    perform public.pelham_fail('422', 'Give the promotion a name.');
  end if;
  if v_kind not in ('amount', 'percent') then
    perform public.pelham_fail('422', 'kind must be amount or percent.');
  end if;
  if v_value is null or v_value <= 0 or (v_kind = 'percent' and v_value > 100) then
    perform public.pelham_fail('422', 'Enter the discount: dollars off, or a percent from 1 to 100.');
  end if;
  select lower(u.email) into v_by from auth.users u where u.id = auth.uid();

  if v_id is null then
    if v_code !~ '^[A-Z0-9]{3,16}$' then
      perform public.pelham_fail('422', 'The code is 3 to 16 letters or numbers, no spaces (e.g. FALL18).');
    end if;
    if exists (select 1 from public.pelham_promotions x where x.code = v_code) then
      perform public.pelham_fail('409', format('%s already exists. Pick another code.', v_code));
    end if;
    insert into public.pelham_promotions
      (code, name, kind, value, per_player, conditions, starts_on, expires_on, usage_limit, active, created_by)
    values
      (v_code, v_name, v_kind, v_value, coalesce((p->>'per_player')::boolean, true),
       nullif(btrim(p->>'conditions'), ''), nullif(p->>'starts_on', '')::date, nullif(p->>'expires_on', '')::date,
       nullif(p->>'usage_limit', '')::integer, coalesce((p->>'active')::boolean, true), v_by)
    returning id into v_id;
  else
    update public.pelham_promotions x
       set name = v_name, kind = v_kind, value = v_value,
           per_player = coalesce((p->>'per_player')::boolean, x.per_player),
           conditions = case when p ? 'conditions' then nullif(btrim(p->>'conditions'), '') else x.conditions end,
           starts_on = case when p ? 'starts_on' then nullif(p->>'starts_on', '')::date else x.starts_on end,
           expires_on = case when p ? 'expires_on' then nullif(p->>'expires_on', '')::date else x.expires_on end,
           usage_limit = case when p ? 'usage_limit' then nullif(p->>'usage_limit', '')::integer else x.usage_limit end,
           active = coalesce((p->>'active')::boolean, x.active),
           updated_at = now()
     where x.id = v_id;
    if not found then
      perform public.pelham_fail('404', 'No such promotion.');
    end if;
  end if;
  return public.pelham_promo_json(v_id);
end;
$$;

create or replace function public.pelham_staff_promotion(p_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_id bigint;
begin
  perform public.pelham_require_staff();
  select p.id into v_id from public.pelham_promotions p where p.code = public.pelham_promo_code(p_code);
  if v_id is null then
    perform public.pelham_fail('404', format('No promotion %s.', public.pelham_promo_code(p_code)));
  end if;
  return public.pelham_promo_json(v_id);
end;
$$;

-- ===== 계산서에 적용 ======================================================

create or replace function public.pelham_staff_bill_apply_promo(p_bill bigint, p_code text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_code text := public.pelham_promo_code(p_code);
  v_promo public.pelham_promotions;
  v_today date := public.pelham_pos_today();
  v_players integer;
  v_fees integer;
  v_taken integer;
  v_amount integer;
  v_by text;
begin
  perform public.pelham_require_staff();
  perform public.pelham_pos_lock_open(p_bill);

  -- 한도를 두 계산대가 같이 넘지 않게 프로모션 줄을 잠근다.
  select * into v_promo from public.pelham_promotions p where p.code = v_code for update;
  if v_promo.id is null then
    perform public.pelham_fail('404', format('No promotion %s.', v_code));
  end if;
  if not v_promo.active then
    perform public.pelham_fail('409', format('%s is paused.', v_code));
  end if;
  if v_promo.starts_on is not null and v_promo.starts_on > v_today then
    perform public.pelham_fail('409', format('%s starts %s.', v_code, v_promo.starts_on));
  end if;
  if v_promo.expires_on is not null and v_promo.expires_on < v_today then
    perform public.pelham_fail('409', format('%s expired %s.', v_code, v_promo.expires_on));
  end if;
  if exists (select 1 from public.pelham_promo_uses x where x.bill_id = p_bill) then
    perform public.pelham_fail('409', 'This bill already has a promo code. Remove it first.');
  end if;
  if v_promo.usage_limit is not null then
    select count(*) into v_taken
      from public.pelham_promo_uses x
      join public.pelham_bills b on b.id = x.bill_id
     where x.promo_id = v_promo.id and b.status in ('paid', 'open');
    if v_taken >= v_promo.usage_limit then
      perform public.pelham_fail('409', format('%s has been used %s of %s times.', v_code, v_taken, v_promo.usage_limit));
    end if;
  end if;

  select coalesce(sum(l.quantity), 0), coalesce(sum(l.line_total), 0) into v_players, v_fees
    from public.pelham_bill_lines l
   where l.bill_id = p_bill and l.active and l.kind = 'tee_player';
  if v_players = 0 or v_fees <= 0 then
    perform public.pelham_fail('422', 'Add the green fee to the bill first, then scan the promo code.');
  end if;

  v_amount := case
    when v_promo.kind = 'percent' then round(v_fees * v_promo.value / 100.0)::integer
    when v_promo.per_player then v_promo.value * v_players
    else v_promo.value
  end;
  v_amount := least(v_amount, v_fees);

  select lower(u.email) into v_by from auth.users u where u.id = auth.uid();
  insert into public.pelham_promo_uses (bill_id, promo_id, amount, applied_by)
  values (p_bill, v_promo.id, v_amount, v_by);
  update public.pelham_bills b set discount = b.discount + v_amount where b.id = p_bill;
  perform public.pelham_pos_recalc(p_bill);
  return public.pelham_pos_bill_json(p_bill);
end;
$$;

create or replace function public.pelham_staff_bill_remove_promo(p_bill bigint)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_amount integer;
begin
  perform public.pelham_require_staff();
  perform public.pelham_pos_lock_open(p_bill);
  delete from public.pelham_promo_uses x where x.bill_id = p_bill returning x.amount into v_amount;
  if v_amount is not null then
    update public.pelham_bills b set discount = greatest(b.discount - v_amount, 0) where b.id = p_bill;
    perform public.pelham_pos_recalc(p_bill);
  end if;
  return public.pelham_pos_bill_json(p_bill);
end;
$$;

-- 이 계산서에 걸린 코드. 없으면 null.
create or replace function public.pelham_staff_bill_promo(p_bill bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_staff();
  return (
    select jsonb_build_object('code', p.code, 'name', p.name, 'kind', p.kind, 'value', p.value,
                              'per_player', p.per_player, 'conditions', p.conditions, 'amount', x.amount)
      from public.pelham_promo_uses x
      join public.pelham_promotions p on p.id = x.promo_id
     where x.bill_id = p_bill
  );
end;
$$;

