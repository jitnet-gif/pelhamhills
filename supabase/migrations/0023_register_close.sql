-- 계산대 마감(Close Register) — Lightspeed R-Series 의 "Closing Totals" 화면과 같은 모양.
--
-- 왜(2026-10-12): 직원들은 Lightspeed 에서 계산대를 닫을 때 **계산대 하나** 의 서랍을 센다 —
-- 현금은 권종별($100 × n …)로, 카드·체크카드는 단말기 마감 전표 금액으로. 0010 의 마감은 **사람별**
-- (팁 나누기용)이라 "Pro Shop 서랍에 얼마가 있어야 하나" 를 보여 주지 못했다. 두 마감은 따로 산다:
--   - 0010 담당자별 마감 = 근무시간 + 팁 나누기(Reports).
--   - 0023 계산대 마감   = 이 계산대 서랍·단말기 숫자 맞추기(계산대 홈의 Close Register).
--
-- 한 줄 = (영업일, 계산대) 하나. 다시 세면 덮어쓴다(0010 과 같다).
--
-- 표의 칸(Lightspeed 와 같은 이름):
--   Start+Adds      = 시작 잔돈. 현금만. 아직 "계산대 열기" 가 없어 계산대마다 고정 $200
--                     (`pelham_register_float`). 열기 화면이 생기면 그 값을 쓰면 된다.
--   Payments        = 그 영업일, 그 계산대(`pelham_bills.station`)에서 결제된 계산서의 결제 줄 (amount + tip).
--                     amount 는 계산서에 들어간 몫뿐이다(거스름돈은 서버로 오지 않는다). 환불된 계산서는
--                     0005·0010 과 같이 뺀다.
--   Withdraws       = 서랍에서 뺀 돈. Payout/Drop 이 아직 없어 0.
--   Total Remaining = Start+Adds + Payments − Withdraws. 서랍(또는 전표)에 있어야 하는 돈.
--   Closing Count   = 센 돈. 현금·카드·체크카드만 센다. 회원 계정·기프트카드·레인체크는 셀 실물이
--                     없어 Lightspeed 의 Credit Account / Gift Card 줄처럼 숫자만 보인다.
--
-- 마감 순간의 Total Remaining 을 같이 적어 둔다. 마감 뒤에 그 계산대에서 결제·환불이 더 있으면
-- 리포트가 `stale` 로 알린다(다시 세면 된다).
--
-- 규칙은 0005·0010 과 같다: `pelham_` 접두사, 테이블은 RLS 켜고 정책 없음, 직원 함수만 authenticated 에게,
-- 오류는 PTxxx. 전제: 0005, 0011(rain_check), 0020(station 'online'). 실행: SQL editor 에 이 파일 전체를
-- 붙여 한 번. 다시 실행해도 안전하다.

do $$
begin
  if to_regclass('public.pelham_bills') is null or to_regclass('public.pelham_bill_payments') is null then
    raise exception '0023 needs 0005 first (pelham_bills / pelham_bill_payments is missing).';
  end if;
  if to_regprocedure('public.pelham_require_staff()') is null or to_regprocedure('public.pelham_pos_today()') is null then
    raise exception '0023 needs 0004 and 0005 first (pelham_require_staff / pelham_pos_today is missing).';
  end if;
end;
$$;

-- ===== 테이블 ==========================================================

create table if not exists public.pelham_register_closes (
  id              bigint generated by default as identity primary key,
  business_date   date not null,
  station         text not null check (station in ('pro_shop', 'snack_bar', 'tee_sheet', 'simulator')),
  opening_float   integer not null check (opening_float >= 0),
  -- 마감 순간의 Total Remaining. {"cash": 20000, "card": 4500, ...} (센트)
  expected        jsonb not null,
  -- 센 돈. {"cash": 20000, "card": 4500, "debit": 0} (센트)
  counted         jsonb not null,
  -- 현금 권종별 개수. {"10000": 1, "2000": 5, ..., "1": 0} + "extra"(센트)
  cash_counts     jsonb not null default '{}'::jsonb,
  note            text,
  closed_by       uuid,
  closed_at       timestamptz not null default now(),
  unique (business_date, station)
);

alter table public.pelham_register_closes enable row level security;
revoke all on public.pelham_register_closes from anon, authenticated;

-- ===== 헬퍼 (직원 확인 없음 — 실행 권한을 아무에게도 주지 않는다) ========

-- 계산대 시작 잔돈(센트). 계산대 열기가 생기기 전까지 고정.
create or replace function public.pelham_register_float(p_station text)
returns integer
language sql
immutable
set search_path = ''
as $$
  select 20000
$$;

-- 표의 줄 순서 = Lightspeed 처럼 현금 먼저, 셀 수 있는 것, 셀 수 없는 것.
create or replace function public.pelham_register_methods()
returns text[]
language sql
immutable
set search_path = ''
as $$
  select array['cash', 'card', 'debit', 'member_account', 'gift_card', 'rain_check']
$$;

-- 한 영업일·한 계산대의 결제수단별 Total Remaining(센트). 결제가 없는 수단도 0 으로 나온다.
create or replace function public.pelham_register_expected(p_date date, p_station text)
returns table (method text, payments integer, payment_count integer)
language sql
stable
set search_path = ''
as $$
  select m.method,
         coalesce(sum(pp.amount + pp.tip), 0)::integer,
         count(pp.id)::integer
    from unnest(public.pelham_register_methods()) as m(method)
    left join public.pelham_bill_payments pp
      on pp.method = m.method
     and pp.bill_id in (select b.id from public.pelham_bills b
                         where b.business_date = p_date and b.station = p_station and b.status = 'paid')
   group by m.method
$$;

-- ===== 직원 함수 ======================================================

-- 계산대 마감 표.
-- {business_date, station, open_bills, rows: [{method, countable, start, payments, payment_count,
--   withdraws, remaining, counted}], totals: {...}, close: {...}|null}
create or replace function public.pelham_staff_register_close_report(p_date date, p_station text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_float integer := public.pelham_register_float(p_station);
  v_close public.pelham_register_closes%rowtype;
  v_rows jsonb;
  v_now jsonb;
begin
  perform public.pelham_require_staff();
  if p_date is null then
    perform public.pelham_fail('422', '''date'' must be an ISO date (YYYY-MM-DD)');
  end if;
  if p_station is null or p_station not in ('pro_shop', 'snack_bar', 'tee_sheet', 'simulator') then
    perform public.pelham_fail('422', format('''%s'' is not a register', p_station));
  end if;

  select * into v_close from public.pelham_register_closes where business_date = p_date and station = p_station;

  select jsonb_agg(jsonb_build_object(
           'method', e.method,
           'countable', e.method in ('cash', 'card', 'debit'),
           'start', case when e.method = 'cash' then v_float else 0 end,
           'payments', e.payments,
           'payment_count', e.payment_count,
           'withdraws', 0,
           'remaining', e.payments + case when e.method = 'cash' then v_float else 0 end,
           'counted', case when v_close.id is null then null else (v_close.counted->>e.method)::integer end
         ) order by array_position(public.pelham_register_methods(), e.method)),
         jsonb_object_agg(e.method, e.payments + case when e.method = 'cash' then v_float else 0 end)
    into v_rows, v_now
    from public.pelham_register_expected(p_date, p_station) e;

  return jsonb_build_object(
    'business_date', to_char(p_date, 'YYYY-MM-DD'),
    'station', p_station,
    -- 아직 결제 안 된 계산서(열린 계산서엔 영업일이 없으니 오늘을 볼 때만).
    'open_bills', case when p_date = public.pelham_pos_today() then (
        select count(*)::integer from public.pelham_bills b
         where b.status = 'open' and b.station = p_station
           and exists (select 1 from public.pelham_bill_lines li where li.bill_id = b.id and li.active))
      else 0 end,
    'rows', v_rows,
    'close', case when v_close.id is null then null else jsonb_build_object(
      'opening_float', v_close.opening_float,
      'expected', v_close.expected,
      'counted', v_close.counted,
      'cash_counts', v_close.cash_counts,
      'note', v_close.note,
      'closed_at', public.pelham_iso(v_close.closed_at),
      -- 센 뒤에 이 계산대에서 결제·환불이 있었다.
      'stale', v_close.expected is distinct from v_now
    ) end
  );
end;
$$;

-- 계산대 마감(또는 다시 세기). p: {counted: {cash, card, debit}, cash_counts: {...}, note?}.
-- 리포트 전체를 돌려준다.
create or replace function public.pelham_staff_register_close_save(p_date date, p_station text, p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_counted jsonb := '{}'::jsonb;
  v_counts jsonb := '{}'::jsonb;
  v_expected jsonb;
  v_method text;
  v_key text;
  v_value integer;
begin
  perform public.pelham_require_staff();
  p := coalesce(p, '{}'::jsonb);
  if p_date is null then
    perform public.pelham_fail('422', '''date'' must be an ISO date (YYYY-MM-DD)');
  end if;
  if p_date > public.pelham_pos_today() then
    perform public.pelham_fail('422', 'You cannot close a register for a day that has not started.');
  end if;
  if p_station is null or p_station not in ('pro_shop', 'snack_bar', 'tee_sheet', 'simulator') then
    perform public.pelham_fail('422', format('''%s'' is not a register', p_station));
  end if;

  -- 센 돈: 현금·카드·체크카드. 비우면 0.
  foreach v_method in array array['cash', 'card', 'debit'] loop
    begin
      v_value := coalesce(nullif(p->'counted'->>v_method, '')::integer, 0);
    exception when others then
      perform public.pelham_fail('422', 'Counts must be whole numbers of cents.');
    end;
    if v_value < 0 then
      perform public.pelham_fail('422', 'Counts cannot be negative.');
    end if;
    v_counted := v_counted || jsonb_build_object(v_method, v_value);
  end loop;

  -- 권종별 개수: 아는 권종 + extra 만 받는다.
  foreach v_key in array array['10000', '5000', '2000', '1000', '500', '200', '100', '25', '10', '5', '1', 'extra'] loop
    begin
      v_value := coalesce(nullif(p->'cash_counts'->>v_key, '')::integer, 0);
    exception when others then
      perform public.pelham_fail('422', 'Cash counts must be whole numbers.');
    end;
    if v_value < 0 then
      perform public.pelham_fail('422', 'Cash counts cannot be negative.');
    end if;
    v_counts := v_counts || jsonb_build_object(v_key, v_value);
  end loop;

  select jsonb_object_agg(e.method, e.payments + case when e.method = 'cash' then public.pelham_register_float(p_station) else 0 end)
    into v_expected
    from public.pelham_register_expected(p_date, p_station) e;

  insert into public.pelham_register_closes as c
    (business_date, station, opening_float, expected, counted, cash_counts, note, closed_by, closed_at)
  values (p_date, p_station, public.pelham_register_float(p_station), v_expected, v_counted, v_counts,
          nullif(btrim(coalesce(p->>'note', '')), ''), auth.uid(), now())
  on conflict (business_date, station) do update
    set opening_float = excluded.opening_float, expected = excluded.expected, counted = excluded.counted,
        cash_counts = excluded.cash_counts, note = excluded.note, closed_by = excluded.closed_by,
        closed_at = excluded.closed_at;

  return public.pelham_staff_register_close_report(p_date, p_station);
end;
$$;

