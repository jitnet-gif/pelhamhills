-- 손님 예약 화면(/book/tee-time, /book/indoor, /book/lookup)을 FastAPI 없이 돌린다.
--
-- 왜: 예약 API(`pelhamhills-api.fly.dev`)가 2026-09-16 Fly.io 체험 종료로 꺼졌다.
-- 정적 사이트(`output: "export"`)는 비밀 키를 들 곳이 없으므로, 브라우저는 공개(anon)
-- 키로 **아래 함수들만** 부른다. 테이블은 그대로 잠겨 있다.
--
-- 규칙
-- - 공유 프로젝트다(GPS 앱·다른 앱과 같은 DB). 테이블·함수 전부 `pelham_` 접두사.
-- - 테이블에는 anon/authenticated 정책을 만들지 않는다(0001·0002 와 같다). 손님이
--   볼 수 있는 것은 함수가 돌려주는 것뿐이다:
--     티타임  → 남은 자리 수와 요금. 다른 손님의 예약 행(이름·전화·이메일)은 절대 안 나간다.
--     실내골프 → 빈 베이 수. 코드 조회는 그 코드의 예약 한 건만(예전 API 와 같다).
-- - 정원 검사와 저장은 한 트랜잭션 안에서 advisory lock 으로 묶는다. FastAPI 의
--   `threading.RLock` 자리를 대신한다. ⚠️ Fly 서버를 다시 켜서 같은 테이블에 쓰게
--   하면 두 쪽의 잠금이 서로를 모른다 — 한쪽만 쓰게 할 것.
-- - 영업 규칙(격자·요금·휴무일)은 `backend/api/routes/tee_sheet.py`,
--   `backend/api/routes/simulator.py` 와 같은 값이다. 바꾸면 양쪽을 같이 바꾼다.
-- - 오류는 `PTxxx` SQLSTATE 로 올린다. PostgREST 가 그 숫자를 HTTP 상태로 쓴다
--   (PT400 → 400, PT409 → 409). 메시지는 손님에게 그대로 보여도 되는 문장이다.
-- - 시각 판단(오늘·지난 시간)은 클럽 현지 시간 America/Toronto 로 한다.
--
-- 실행: SQL editor 에 이 파일 전체를 붙여 한 번. 다시 실행해도 안전하다(시드는 비어 있을 때만).

-- 0002 는 RLS 만 켰다(정책 없음 → 0행). 이제 공개 키가 이 DB 에 실제로 들어오므로
-- 테이블 권한 자체도 걷어 낸다. service_role(Fly 백엔드)은 영향이 없다.
revoke all on public.pelham_tee_bookings from anon, authenticated;

