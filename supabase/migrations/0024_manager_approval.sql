-- 매니저 승인(Manager override) — 환불·레인체크·선수 삭제·결제 취소·가격 변경은 매니저 PIN 이 있어야 된다.
--
-- 왜(2026-10-13): 프로 샵 계정 하나로 누구나 돈을 되돌릴 수 있었다. Lightspeed 처럼 그 순간 매니저가
-- 와서 PIN 을 치게 한다. 화면이 아니라 **서버**가 막는다 — 화면을 우회해 함수를 직접 불러도 막힌다.
--
-- 흐름:
--   1) 직원이 막힌 일을 하면 함수가 PT428 로 거절한다. 메시지 끝에 `[approval:<action>:<ref>]` 가 붙는다.
--   2) 화면이 PIN 창을 띄우고 `pelham_staff_manager_approve(pin, action, ref)` 를 부른다.
--   3) PIN 이 맞으면 승인 한 줄이 남는다(누가·누구를·무엇을·언제). 같은 직원·같은 일·같은 대상에 10분 유효.
--   4) 화면이 원래 요청을 다시 보낸다 — 이번엔 통과한다.
--
-- 막는 일(action · ref):
--   refund        · 계산서 id  — 결제된 계산서 환불(pelham_staff_bill_refund), 결제 뒤 카드 환불
--                                (pelham_staff_terminal_begin kind=refund). 계산 중 결제 줄 지우기는 막지 않는다.
--   rain_check    · 예약 id    — 레인체크 발행·무효.
--   remove_player · 예약 id    — 예약에서 선수 빼기.
--   mark_unpaid   · 예약 id    — 선수의 결제 표시 지우기(paid=false).
--   price         · 예약 id    — 그린피(pelham_staff_booking_patch 의 rate)·카트 요금(player_patch 의 cartFee) 바꾸기.
--                                카트를 켜서 서버가 요금을 채우는 것과 새 예약의 요금은 막지 않는다.
--
-- 2026-10-14: `price` 를 더했다. 이미 0024 를 돌렸어도 이 파일 전체를 다시 실행하면 된다.
--
-- 매니저 PIN 은 SQL editor 에서 넣는다(화면이 없다). 4~8자리 숫자, 매니저마다 달라야 한다:
--   select public.pelham_manager_pin_set('Francis', '2468');        -- 넣기·바꾸기
--   select public.pelham_manager_pin_set('Francis', null);          -- 끄기
--   select name, active, updated_at from public.pelham_managers;    -- 목록
-- PIN 은 bcrypt 해시로만 남는다. 10분에 5번 틀리면 그 직원 계정은 10분 동안 승인을 못 받는다.
--
-- 구현: 원래 함수를 `<이름>_ungated` 로 바꾸고 같은 이름·같은 인자의 얇은 함수를 새로 둔다. 원래 함수의
-- 본문을 이 파일에 복사하지 않으려는 것이다. **0004·0005·0011·0021 을 다시 실행하면 게이트가 풀린다** —
-- 그 뒤엔 이 파일을 다시 실행하면 된다(다시 실행해도 안전하다).
--
-- 규칙은 0005 와 같다: `pelham_` 접두사, 테이블은 RLS 켜고 정책 없음, 직원 함수만 authenticated 에게,
-- 오류는 PTxxx. 전제: 0004, 0005, 0011, 0021. 실행: SQL editor 에 이 파일 전체를 붙여 한 번.

do $$
begin
  if to_regprocedure('public.pelham_require_staff()') is null then
    raise exception '0024 needs 0004 first (pelham_require_staff is missing).';
  end if;
  if to_regclass('public.pelham_bills') is null then
    raise exception '0024 needs 0005 first (pelham_bills is missing).';
  end if;
  if to_regclass('public.pelham_rain_checks') is null then
    raise exception '0024 needs 0011 first (pelham_rain_checks is missing).';
  end if;
  if to_regprocedure('public.pelham_staff_terminal_begin(jsonb)') is null then
    raise exception '0024 needs 0021 first (pelham_staff_terminal_begin is missing).';
  end if;
end;
$$;

