create or replace function public.pelham_staff_rain_check_void(p_code text, p_reason text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_booking text;
begin
  perform public.pelham_require_staff();
  select r.booking_id into v_booking from public.pelham_rain_checks r where r.code = upper(btrim(coalesce(p_code, '')));
  if v_booking is not null then
    perform public.pelham_require_manager('rain_check', v_booking, 'voiding this rain check');
  end if;
  return public.pelham_staff_rain_check_void_ungated(p_code, p_reason);
end;
$$;

