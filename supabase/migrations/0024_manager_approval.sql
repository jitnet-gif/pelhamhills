create table if not exists public.pelham_managers (
  id          bigint generated by default as identity primary key,
  name        text not null unique check (btrim(name) <> ''),
  pin_hash    text,
  active      boolean not null default true,
  updated_at  timestamptz not null default now()
);

-- 승인 시도 전부(맞은 것·틀린 것). 틀린 것은 manager_id 가 비어 있다.
create table if not exists public.pelham_manager_approvals (
  id            bigint generated by default as identity primary key,
  ok            boolean not null,
  manager_id    bigint references public.pelham_managers (id),
  action        text not null,
  ref           text not null,
  requested_by  uuid,
  created_at    timestamptz not null default now()
);
create index if not exists pelham_manager_approvals_lookup_idx
  on public.pelham_manager_approvals (requested_by, action, ref, created_at desc) where ok;
create index if not exists pelham_manager_approvals_fail_idx
  on public.pelham_manager_approvals (requested_by, created_at desc) where not ok;

alter table public.pelham_managers enable row level security;
alter table public.pelham_manager_approvals enable row level security;
revoke all on public.pelham_managers from anon, authenticated;
revoke all on public.pelham_manager_approvals from anon, authenticated;

-- ===== 헬퍼 (실행 권한을 아무에게도 주지 않는다) =========================

-- 매니저 PIN 넣기·바꾸기·끄기. SQL editor(postgres)에서만 부른다.
create or replace function public.pelham_manager_pin_set(p_name text, p_pin text)
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_name text := btrim(coalesce(p_name, ''));
begin
  if v_name = '' then
    raise exception 'Give the manager a name.';
  end if;
  if p_pin is null then
    update public.pelham_managers set active = false, pin_hash = null, updated_at = now() where name = v_name;
    return format('%s can no longer approve.', v_name);
  end if;
  if p_pin !~ '^[0-9]{4,8}$' then
    raise exception 'A PIN is 4 to 8 digits.';
  end if;
  if exists (select 1 from public.pelham_managers m
              where m.active and m.pin_hash is not null and m.name <> v_name
                and m.pin_hash = extensions.crypt(p_pin, m.pin_hash)) then
    raise exception 'Another manager already uses that PIN. Pick a different one.';
  end if;
  insert into public.pelham_managers (name, pin_hash, active, updated_at)
  values (v_name, extensions.crypt(p_pin, extensions.gen_salt('bf')), true, now())
  on conflict (name) do update set pin_hash = excluded.pin_hash, active = true, updated_at = now();
  return format('%s can approve with the new PIN.', v_name);
end;
$$;

-- 지금 직원에게 이 일의 승인이 있나. 없으면 PT428 로 거절한다(메시지 끝의 꼬리표를 화면이 읽는다).
create or replace function public.pelham_require_manager(p_action text, p_ref text, p_what text)
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if exists (select 1 from public.pelham_manager_approvals a
              where a.ok and a.requested_by is not distinct from auth.uid()
                and a.action = p_action and a.ref = p_ref
                and a.created_at > now() - interval '10 minutes') then
    return;
  end if;
  perform public.pelham_fail('428', format('A manager must approve %s. [approval:%s:%s]', p_what, p_action, p_ref));
end;
$$;

-- ===== 직원 함수 ======================================================

-- 매니저 PIN 확인. 맞으면 {manager, action, ref, expires_at}.
create or replace function public.pelham_staff_manager_approve(p_pin text, p_action text, p_ref text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_manager public.pelham_managers%rowtype;
  v_at timestamptz := now();
begin
  perform public.pelham_require_staff();
  if p_action is null or p_action not in ('refund', 'rain_check', 'remove_player', 'mark_unpaid', 'price') then
    perform public.pelham_fail('422', 'Unknown approval.');
  end if;
  if coalesce(btrim(p_ref), '') = '' then
    perform public.pelham_fail('422', 'Nothing to approve.');
  end if;
  if (select count(*) from public.pelham_manager_approvals a
       where not a.ok and a.requested_by is not distinct from auth.uid()
         and a.created_at > now() - interval '10 minutes') >= 5 then
    perform public.pelham_fail('429', 'Too many wrong PINs. Wait 10 minutes and try again.');
  end if;

  select * into v_manager from public.pelham_managers m
   where m.active and m.pin_hash is not null and coalesce(p_pin, '') ~ '^[0-9]{4,8}$'
     and m.pin_hash = extensions.crypt(p_pin, m.pin_hash)
   limit 1;

  insert into public.pelham_manager_approvals (ok, manager_id, action, ref, requested_by, created_at)
  values (v_manager.id is not null, v_manager.id, p_action, btrim(p_ref), auth.uid(), v_at);

  if v_manager.id is null then
    -- 실패 기록은 남아야 한다 — 예외로 끝내면 위 insert 가 같이 되돌려진다. 그래서 값으로 알린다.
    return jsonb_build_object('approved', false, 'message', 'That PIN is not a manager PIN.');
  end if;
  return jsonb_build_object(
    'approved', true,
    'manager', v_manager.name,
    'action', p_action,
    'ref', btrim(p_ref),
    'expires_at', public.pelham_iso(v_at + interval '10 minutes'));
end;
$$;

-- ===== 게이트 ==========================================================
--
-- 원래 함수 → <이름>_ungated. 이미 바뀌어 있고 지금 이름의 본문이 게이트가 아니면(옛 마이그레이션을 다시 돌림)
-- 옛 _ungated 를 버리고 새 본문을 다시 옮긴다.

do $$
declare
  v_sig record;
  v_gate text;
begin
  for v_sig in
    select * from (values
      ('pelham_staff_bill_refund', 'bigint, text'),
      ('pelham_staff_terminal_begin', 'jsonb'),
      ('pelham_staff_rain_check_issue', 'jsonb'),
      ('pelham_staff_rain_check_void', 'text, text'),
      ('pelham_staff_player_remove', 'text, text'),
      ('pelham_staff_player_patch', 'text, text, jsonb'),
      ('pelham_staff_booking_patch', 'text, jsonb')
    ) as t(fn, args)
  loop
    -- 주석이 아니라 본문으로 본다. 옛 마이그레이션의 `create or replace` 는 본문만 바꾸고 주석은 남긴다.
    select p.prosrc into v_gate from pg_proc p
     where p.oid = to_regprocedure(format('public.%s(%s)', v_sig.fn, v_sig.args));
    if v_gate like '%pelham_require_manager%' then
      continue;
    end if;
    if to_regprocedure(format('public.%s_ungated(%s)', v_sig.fn, v_sig.args)) is not null then
      execute format('drop function public.%s_ungated(%s)', v_sig.fn, v_sig.args);
    end if;
    execute format('alter function public.%s(%s) rename to %s_ungated', v_sig.fn, v_sig.args, v_sig.fn);
  end loop;
end;
$$;

create or replace function public.pelham_staff_bill_refund(p_bill bigint, p_reason text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_staff();
  perform public.pelham_require_manager('refund', p_bill::text, 'this refund');
