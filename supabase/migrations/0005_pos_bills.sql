-- 프로 샵·스낵바 계산대와 **합산 계산서**를 FastAPI 없이 Supabase 에서 돌린다.
--
-- 왜: 리테일 API(`backend/api/routes/retail.py`)는 Fly 서버와 함께 꺼졌다(2026-09-16).
-- 클럽은 2026-09-29 에 두 가지를 정했다.
--   1) 리테일·스낵바를 티 시트처럼 Supabase 로 옮긴다(Fly 는 살리지 않는다).
--   2) 그린피·프로 샵·스낵바를 **계산서 한 장**으로 받는다.
--
-- 모델: 모든 판매는 계산서(`pelham_bills`)다. 공 한 줄을 사 가는 손님도 계산서 한 장이다.
--   - 계산서는 열린 채(open) DB 에 있다. 그래서 티 시트에서 그린피를 담고 리테일 화면으로
--     넘어가 모자를 담아도 같은 계산서가 이어진다(화면 상태가 아니라 DB 상태).
--   - 줄(`pelham_bill_lines`)은 상품(product) 또는 티 시트 플레이어(tee_player)다.
--   - 결제(`pelham_bill_payments`)는 여러 줄이 될 수 있다(분할 결제). 합이 계산서 합계와 같아야 한다.
--   - 결제가 끝나는 순간(한 트랜잭션)에 재고를 깎고, 티 시트 플레이어를 paid 로 바꾸고,
--     영수증 번호를 매긴다. 결제 전에는 아무것도 깎지 않는다("승인 먼저, 기록은 나중").
--
-- 카드: Chase 단말기(Ingenico DX8000)는 아직 앱과 연동되지 않았다(semi-integrated 규격은
-- Chase 에서 받아야 한다). 그때까지 카드·체크카드는 **단말기에서 직접 금액을 치고**, 단말기가
-- 찍어 준 승인번호를 여기 적는다(`entry = 'keyed'`). 승인번호가 없는 카드 결제는 받지 않는다 —
-- "직원 토글만으로 paid 가 되면 안 된다"(2026-09-10 결정). 승인번호·카드 끝 4자리는 단말기가
-- 실제로 준 값만 적는다. 카드 번호·유효기간은 어디에도 저장하지 않는다.
--
-- 규칙 (0004 와 같다)
-- - 공유 프로젝트다. 테이블·함수 전부 `pelham_` 접두사.
-- - 테이블은 RLS 를 켜고 정책을 두지 않는다. 직원이 닿는 문은 `pelham_staff_*` 함수뿐이고,
--   함수마다 `pelham_require_staff()` 가 첫 줄이다.
-- - 금액은 **센트 정수**. 티 시트는 달러 numeric 이라 이 파일에서 한 번만 센트로 바꾼다.
-- - 세금(HST 13%)은 계산서 전체에 **한 번** 매기고 은행가 반올림을 쓴다(파이썬 `round()`,
--   `lib/retail/types.ts` 의 `computeTax` 와 같은 값). Postgres `round()` 는 0.5 를 위로
--   올려서 1센트가 어긋난다.
-- - 오류는 `PTxxx` SQLSTATE. PT404=없음, PT409=상태 충돌, PT422=입력 오류.
--
-- 전제: 0003(`pelham_fail`, `pelham_iso`)과 0004(`pelham_require_staff`, 티 시트 헬퍼)가
-- 먼저 돌아 있어야 한다.
--
-- 실행: SQL editor 에 이 파일 전체를 붙여 한 번. 다시 실행해도 안전하다.

-- ===== 먼저 확인 ======================================================
-- 0003·0004 가 이 프로젝트에 돌아 있어야 한다. 빠진 게 있으면 무엇이 빠졌는지 말하고 멈춘다
-- (중간까지 만들다 깨지는 것보다 낫다).
do $$
declare
  v_missing text[] := '{}';
  v_name text;
begin
  foreach v_name in array array['pelham_fail', 'pelham_iso', 'pelham_local_now', 'pelham_require_staff',
                                 'pelham_tee_audit', 'pelham_tee_save', 'pelham_tee_lock'] loop
    if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                    where n.nspname = 'public' and p.proname = v_name) then
      v_missing := v_missing || (v_name || '()');
    end if;
  end loop;
  if to_regclass('public.pelham_tee_bookings') is null then
    v_missing := v_missing || 'pelham_tee_bookings'::text;
  end if;
  if cardinality(v_missing) > 0 then
    raise exception '0005 needs 0003 and 0004 first. Missing: %', array_to_string(v_missing, ', ');
  end if;
end;
$$;

