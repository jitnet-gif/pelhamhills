-- 상품 입력 검증 + 정규화. 생성·수정이 같이 쓴다.
create or replace function public.pelham_pos_check_product(p jsonb)
returns void
language plpgsql
immutable
set search_path = ''
as $$
begin
  if p ? 'category' and (p->>'category') not in
     ('Apparel', 'Equipment', 'Balls', 'Accessories', 'Food & Beverage', 'Rentals') then
    perform public.pelham_fail('422', format('''%s'' is not a product category', p->>'category'));
  end if;
  if p ? 'price' and coalesce((p->>'price')::integer, -1) < 0 then
    perform public.pelham_fail('422', 'Price must be zero or more (cents).');
  end if;
  if p ? 'cost' and coalesce((p->>'cost')::integer, 0) < 0 then
    perform public.pelham_fail('422', 'Cost cannot be negative.');
  end if;
  if p ? 'stock' and jsonb_typeof(p->'stock') <> 'null' and (p->>'stock')::integer < 0 then
    perform public.pelham_fail('422', 'Stock cannot be negative. Leave it empty for rentals.');
  end if;
  if p ? 'sku' and length(btrim(coalesce(p->>'sku', ''))) not between 1 and 64 then
    perform public.pelham_fail('422', 'SKU must be 1–64 characters.');
  end if;
  if p ? 'name' and length(btrim(coalesce(p->>'name', ''))) not between 1 and 120 then
    perform public.pelham_fail('422', 'Name must be 1–120 characters.');
  end if;
end;
$$;

-- ===== 티 시트 보호 ====================================================
-- 계산서로 받은 그린피를 티 시트에서 "Mark unpaid" 하거나, 그 플레이어·예약을 지우면
-- 계산서(돈을 받았다)와 티 시트(안 받았다)가 갈라진다. 그 길은 계산서 환불 하나로만 연다.
create or replace function public.pelham_pos_guard_tee()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  l record;
  v_player jsonb;
begin
  for l in
    select li.player_id, li.name, b.receipt_no
      from public.pelham_bill_lines li
      join public.pelham_bills b on b.id = li.bill_id
     where li.booking_id = old.id
       and li.kind = 'tee_player'
       and li.active
       and b.status = 'paid'
  loop
    if tg_op = 'DELETE' then
      perform public.pelham_fail('409', format(
        'This reservation was paid on bill %s. Refund that bill before deleting it.', l.receipt_no));
    end if;
    v_player := public.pelham_pos_find_player(new.doc, l.player_id);
    if v_player is null or not coalesce((v_player->>'paid')::boolean, false) then
      perform public.pelham_fail('409', format(
        '%s was paid on bill %s. Refund that bill instead of clearing the payment or removing the player.',
        l.name, l.receipt_no));
    end if;
  end loop;
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists pelham_pos_guard_tee on public.pelham_tee_bookings;
create trigger pelham_pos_guard_tee
  before update or delete on public.pelham_tee_bookings
  for each row execute function public.pelham_pos_guard_tee();

