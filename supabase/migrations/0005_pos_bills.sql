-- 일 마감(기존 `RetailDailyReport` 모양). 환불된 계산서는 금액에서 빼고 건수로만 센다.
-- by_category 에는 그린피가 'Green Fees' 로 함께 잡힌다 — 계산서 한 장에 섞여 팔리기 때문이다.
-- by_station 은 프로 샵·스낵바·티 시트 어디서 연 계산서인지로 나눈다.
create or replace function public.pelham_staff_pos_report_daily(p_date date)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_staff();
  return (
    with live as (
      select * from public.pelham_bills where business_date = p_date and status = 'paid'
    ), refunded as (
      select * from public.pelham_bills where business_date = p_date and status = 'refunded'
    ), lines as (
      select li.* from public.pelham_bill_lines li join live b on b.id = li.bill_id where li.active
    ), pays as (
      select pp.* from public.pelham_bill_payments pp join live b on b.id = pp.bill_id
    )
    select jsonb_build_object(
      'business_date', to_char(p_date, 'YYYY-MM-DD'),
      'sale_count', (select count(*) from live),
      'gross', (select coalesce(sum(subtotal), 0) from live),
      'discount', (select coalesce(sum(discount), 0) from live),
      'tax', (select coalesce(sum(tax), 0) from live),
      'net', (select coalesce(sum(total), 0) from live),
      'tips', (select coalesce(sum(tip), 0) from live),
      'refunded_count', (select count(*) from refunded),
      'refunded_total', (select coalesce(sum(total), 0) from refunded),
      'by_payment', coalesce((
        select jsonb_agg(jsonb_build_object('method', method, 'count', n, 'total', t)
                         order by array_position(array['cash', 'card', 'debit', 'member_account', 'gift_card'], method))
          from (select method, count(*) as n, sum(amount) as t from pays group by method) s
      ), '[]'::jsonb),
      'by_category', coalesce((
        select jsonb_agg(jsonb_build_object('category', category, 'quantity', q, 'total', t)
                         order by array_position(array['Green Fees', 'Apparel', 'Equipment', 'Balls',
                                                       'Accessories', 'Food & Beverage', 'Rentals'], category))
          from (select category, sum(quantity) as q, sum(line_total) as t from lines group by category) s
      ), '[]'::jsonb),
      'by_station', coalesce((
        select jsonb_agg(jsonb_build_object('station', station, 'count', n, 'total', t) order by station)
          from (select station, count(*) as n, sum(total) as t from live group by station) s
      ), '[]'::jsonb),
      'top_products', coalesce((
        select jsonb_agg(jsonb_build_object('product_id', product_id, 'name', name, 'quantity', q, 'total', t)
                         order by q desc, t desc, product_id)
          from (select product_id, min(name) as name, sum(quantity) as q, sum(line_total) as t
                  from lines where kind = 'product' group by product_id
                 order by q desc, t desc, product_id limit 5) s
      ), '[]'::jsonb)
    )
  );
end;
$$;

