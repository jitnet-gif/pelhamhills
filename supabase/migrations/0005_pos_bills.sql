-- HST 13%, 은행가 반올림. taxable 850 → 110 (half-up 이면 111). `computeTax` 와 같은 값.
create or replace function public.pelham_pos_tax(p_taxable integer)
returns integer
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_scaled bigint := greatest(coalesce(p_taxable, 0), 0)::bigint * 13;
  v_q bigint := v_scaled / 100;
  v_r bigint := v_scaled % 100;
begin
  if v_r > 50 or (v_r = 50 and v_q % 2 = 1) then
    v_q := v_q + 1;
  end if;
  return v_q::integer;
end;
$$;

