-- 상품 담기. 같은 상품이 이미 있으면 수량을 더한다(스캔 두 번 = 2개).
create or replace function public.pelham_staff_bill_add_product(p_bill bigint, p_product integer, p_quantity integer default 1)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_product public.pelham_retail_products;
begin
  perform public.pelham_require_staff();
  perform public.pelham_pos_lock_open(p_bill);
  if coalesce(p_quantity, 0) < 1 or p_quantity > 9999 then
    perform public.pelham_fail('422', 'Quantity must be between 1 and 9999.');
  end if;
  select * into v_product from public.pelham_retail_products where id = p_product;
  if v_product.id is null then
    perform public.pelham_fail('404', 'Product not found');
  end if;
  if not v_product.is_active then
    perform public.pelham_fail('409', format('%s (%s) is not for sale.', v_product.name, v_product.sku));
  end if;

  insert into public.pelham_bill_lines (bill_id, kind, product_id, sku, name, category, quantity, unit_price, line_total)
  values (p_bill, 'product', v_product.id, v_product.sku, v_product.name, v_product.category,
          p_quantity, v_product.price, p_quantity * v_product.price)
  on conflict (bill_id, product_id) where kind = 'product'
  do update set quantity = public.pelham_bill_lines.quantity + excluded.quantity,
                line_total = (public.pelham_bill_lines.quantity + excluded.quantity) * public.pelham_bill_lines.unit_price
                             - least(public.pelham_bill_lines.discount,
                                     (public.pelham_bill_lines.quantity + excluded.quantity) * public.pelham_bill_lines.unit_price);

  perform public.pelham_pos_recalc(p_bill);
  return public.pelham_pos_bill_json(p_bill);
end;
$$;

-- 줄 하나 고치기. p: {quantity, discount}. quantity 0 이면 줄을 지운다.
-- 그린피 줄은 수량을 바꿀 수 없다(한 사람 = 한 줄). 할인만 된다.
create or replace function public.pelham_staff_bill_line_update(p_bill bigint, p_line bigint, p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  l public.pelham_bill_lines;
  v_qty integer;
  v_discount integer;
begin
  perform public.pelham_require_staff();
  perform public.pelham_pos_lock_open(p_bill);
  select * into l from public.pelham_bill_lines where id = p_line and bill_id = p_bill;
  if l.id is null then
    perform public.pelham_fail('404', 'Line not found on this bill');
  end if;
  p := coalesce(p, '{}'::jsonb);

  v_qty := coalesce((p->>'quantity')::integer, l.quantity);
  if l.kind = 'tee_player' and v_qty not in (0, 1) then
    perform public.pelham_fail('422', 'A green fee line is one player. Remove it or keep it.');
  end if;
  if v_qty = 0 then
    delete from public.pelham_bill_lines where id = p_line;
  else
    if v_qty < 0 or v_qty > 9999 then
      perform public.pelham_fail('422', 'Quantity must be between 0 and 9999.');
    end if;
    v_discount := coalesce((p->>'discount')::integer, l.discount);
    if v_discount < 0 then
      perform public.pelham_fail('422', 'Discount cannot be negative.');
    end if;
    -- 줄 할인은 줄 합계를 넘지 못한다. 넘으면 잘라 둔다(화면도 같은 값을 보여 준다).
    v_discount := least(v_discount, v_qty * l.unit_price);
    update public.pelham_bill_lines
       set quantity = v_qty, discount = v_discount, line_total = v_qty * unit_price - v_discount
     where id = p_line;
  end if;

  perform public.pelham_pos_recalc(p_bill);
  return public.pelham_pos_bill_json(p_bill);
end;
$$;

-- 계산서 머리 고치기. p: {discount, cashier, note, label}
create or replace function public.pelham_staff_bill_update(p_bill bigint, p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_staff();
  perform public.pelham_pos_lock_open(p_bill);
  p := coalesce(p, '{}'::jsonb);
  if p ? 'discount' and coalesce((p->>'discount')::integer, -1) < 0 then
    perform public.pelham_fail('422', 'Discount must be zero or more (cents).');
  end if;
  update public.pelham_bills
     set discount = coalesce((p->>'discount')::integer, discount),
         cashier = case when p ? 'cashier' then nullif(btrim(coalesce(p->>'cashier', '')), '') else cashier end,
         note = case when p ? 'note' then nullif(btrim(coalesce(p->>'note', '')), '') else note end,
         label = case when p ? 'label' then nullif(btrim(coalesce(p->>'label', '')), '') else label end
   where id = p_bill;
  perform public.pelham_pos_recalc(p_bill);
  return public.pelham_pos_bill_json(p_bill);
end;
$$;

-- 티 시트 플레이어의 그린피를 담는다. p_players 가 비어 있으면 그 예약에서 아직 안 낸 사람 전부.
-- 이미 낸 사람·취소된 사람은 건너뛰지 않고 거절한다 — 직원이 "넷 다 담겼다"고 믿으면 안 된다.
create or replace function public.pelham_staff_bill_add_tee(p_bill bigint, p_booking text, p_players text[] default null)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_doc jsonb;
  v_player jsonb;
  v_ids text[];
  v_id text;
  v_other text;
  v_price integer;
begin
  perform public.pelham_require_staff();
  perform public.pelham_pos_lock_open(p_bill);

  select t.doc into v_doc from public.pelham_tee_bookings t where t.id = p_booking;
  if v_doc is null then
    perform public.pelham_fail('404', 'Booking not found');
  end if;

  if p_players is null or cardinality(p_players) = 0 then
    select coalesce(array_agg(e.value->>'id' order by e.ord), '{}')
      into v_ids
      from jsonb_array_elements(coalesce(v_doc->'players', '[]'::jsonb)) with ordinality as e(value, ord)
     where not coalesce((e.value->>'paid')::boolean, false)
       and not coalesce((e.value->>'cancelled')::boolean, false)
       and not exists (select 1 from public.pelham_bill_lines li
                        where li.booking_id = p_booking and li.player_id = e.value->>'id'
                          and li.kind = 'tee_player' and li.active);
    if cardinality(v_ids) = 0 then
      perform public.pelham_fail('409', 'Everyone on this reservation has paid or is already on a bill.');
    end if;
  else
    v_ids := p_players;
  end if;

  foreach v_id in array v_ids loop
    v_player := public.pelham_pos_find_player(v_doc, v_id);
    if v_player is null then
      perform public.pelham_fail('404', 'Player not found on this reservation');
    end if;
    if coalesce((v_player->>'cancelled')::boolean, false) then
      perform public.pelham_fail('409', format('%s is cancelled.', coalesce(v_player->>'name', 'This player')));
    end if;
    if coalesce((v_player->>'paid')::boolean, false) then
      perform public.pelham_fail('409', format('%s has already paid.', coalesce(v_player->>'name', 'This player')));
    end if;
    select coalesce(b.receipt_no, b.label, '#' || b.id) into v_other
      from public.pelham_bill_lines li join public.pelham_bills b on b.id = li.bill_id
     where li.booking_id = p_booking and li.player_id = v_id and li.kind = 'tee_player' and li.active
     limit 1;
    if v_other is not null then
      perform public.pelham_fail('409', format('%s is already on bill %s.',
                                               coalesce(v_player->>'name', 'This player'), v_other));
    end if;

    v_price := public.pelham_pos_tee_price(v_doc, v_player);
    insert into public.pelham_bill_lines
      (bill_id, kind, sku, name, category, quantity, unit_price, line_total,
       booking_id, player_id, tee_date, tee_time)
    values
      (p_bill, 'tee_player', 'TEE', public.pelham_pos_tee_line_name(v_doc, v_player), 'Green Fees',
       1, v_price, v_price, p_booking, v_id, (v_doc->>'date')::date, v_doc->>'time');
  end loop;

  perform public.pelham_pos_recalc(p_bill);
  return public.pelham_pos_bill_json(p_bill);
end;
$$;

