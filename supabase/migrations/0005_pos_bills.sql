-- 계산서 한 장 → 화면이 받는 모양. 결제된 계산서는 기존 `Sale`(lib/retail/types.ts)과
-- 필드 이름이 같다 — 매출 탭과 영수증이 그대로 읽는다. 거기에 lines[].kind, payments[],
-- status, station 이 더 붙는다.
create or replace function public.pelham_pos_bill_json(p_bill bigint)
returns jsonb
language sql
stable
set search_path = ''
as $$
  select jsonb_build_object(
    'id', b.id,
    'status', b.status,
    'station', b.station,
    'label', b.label,
    'receipt_no', b.receipt_no,
    'business_date', to_char(b.business_date, 'YYYY-MM-DD'),
    'checkout_id', b.checkout_id,
    'lines', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', l.id,
               'kind', l.kind,
               'product_id', l.product_id,
               'sku', l.sku,
               'name', l.name,
               'category', l.category,
               'quantity', l.quantity,
               'unit_price', l.unit_price,
               'discount', l.discount,
               'line_total', l.line_total,
               'booking_id', l.booking_id,
               'player_id', l.player_id,
               'tee_date', to_char(l.tee_date, 'YYYY-MM-DD'),
               'tee_time', l.tee_time
             ) order by l.id)
        from public.pelham_bill_lines l
       where l.bill_id = b.id
         and (l.active or b.status in ('refunded', 'void'))
    ), '[]'::jsonb),
    'payments', coalesce((
      select jsonb_agg(jsonb_build_object(
               'method', p.method,
               'amount', p.amount,
               'tip', p.tip,
               'entry', p.entry,
               'auth_code', p.auth_code,
               'card_last4', p.card_last4,
               'terminal', p.terminal
             ) order by p.id)
        from public.pelham_bill_payments p
       where p.bill_id = b.id
    ), '[]'::jsonb),
    -- 기존 `Sale.payment_method` 자리: 첫 결제 수단. 분할 결제면 payments[] 를 본다.
    'payment_method', (select p.method from public.pelham_bill_payments p
                        where p.bill_id = b.id order by p.id limit 1),
    'subtotal', b.subtotal,
    'discount', b.discount,
    'tax', b.tax,
    'total', b.total,
    'tip', b.tip,
    'cashier', b.cashier,
    'note', b.note,
    'opened_at', public.pelham_iso(b.opened_at),
    'paid_at', public.pelham_iso(b.paid_at),
    'refunded_at', public.pelham_iso(b.refunded_at),
    'refund_reason', b.refund_reason,
    -- `Sale.created_at` 은 영수증 시각이다. 결제된 계산서는 결제 시각을 쓴다.
    'created_at', public.pelham_iso(coalesce(b.paid_at, b.opened_at))
  )
  from public.pelham_bills b
  where b.id = p_bill
$$;

-- 열린 계산서를 잠그고 가져온다. 없거나 이미 닫혔으면 여기서 끝난다.
create or replace function public.pelham_pos_lock_open(p_bill bigint)
returns public.pelham_bills
language plpgsql
volatile
set search_path = ''
as $$
declare
  v public.pelham_bills;
begin
