-- 한 플레이어가 내는 그린피(센트). 티 시트 리포트(`pelham_tee_daily_report`)와 같은 규칙:
-- 예약의 rate + (카트를 쓰면) 카트 요금. 둘 다 세전 달러.
create or replace function public.pelham_pos_tee_price(p_doc jsonb, p_player jsonb)
returns integer
language sql
immutable
set search_path = ''
as $$
  select round((coalesce((p_doc->>'rate')::numeric, 0)
                + case when coalesce((p_player->>'cart')::boolean, false)
                       then coalesce((p_player->>'cartFee')::numeric, 0) else 0 end) * 100)::integer
$$;

-- 예약 doc 안에서 플레이어 하나.
create or replace function public.pelham_pos_find_player(p_doc jsonb, p_player text)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select e.value
    from jsonb_array_elements(coalesce(p_doc->'players', '[]'::jsonb)) as e(value)
   where e.value->>'id' = p_player
   limit 1
$$;

-- 재고 한 번 움직이기: 원장 한 줄 + 상품의 재고 사본. 재고를 세지 않는 품목은 원장만 남기지 않는다.
create or replace function public.pelham_pos_move(
  p_product integer, p_delta integer, p_reason text, p_bill bigint, p_note text
)
returns void
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_stock integer;
begin
  select p.stock into v_stock from public.pelham_retail_products p where p.id = p_product for update;
  if v_stock is null or p_delta = 0 then
    return;
  end if;
  update public.pelham_retail_products
     set stock = stock + p_delta, updated_at = now()
   where id = p_product;
  insert into public.pelham_retail_stock_moves (product_id, qty_delta, reason, bill_id, note, created_by)
  values (p_product, p_delta, p_reason, p_bill, p_note, auth.uid());
end;
$$;

-- 열린 계산서의 금액을 다시 맞춘다. 그린피 줄은 **지금의 예약 doc** 에서 다시 값을 읽는다
-- (담은 뒤에 카트를 붙였으면 따라간다). 결제·취소된 플레이어는 값을 바꾸지 않고 둔다 —
-- 결제 함수가 그 줄을 거절한다.
create or replace function public.pelham_pos_recalc(p_bill bigint)
returns void
language plpgsql
volatile
set search_path = ''
as $$
declare
  l record;
  v_doc jsonb;
  v_player jsonb;
  v_price integer;
  v_subtotal integer;
  v_discount integer;
  v_taxable integer;
  v_status text;
begin
  -- 계산서 행을 먼저 잠근다. 안 잠그면 목록 새로고침의 재계산이 동시에 담긴 상품보다 먼저
  -- 합계를 읽고 나중에 써서, 화면(=직원이 단말기에 치는 금액)이 옛 합계로 돌아간다.
  select b.status into v_status from public.pelham_bills b where b.id = p_bill for update;
  -- 닫힌 계산서(결제·환불·취소)는 건드리지 않는다. 목록을 모은 뒤 그 사이에 닫힌 계산서를
  -- 다시 계산하면, 줄이 모두 무효인 환불 계산서의 합계가 0 으로 덮인다.
  if v_status is distinct from 'open' then
    return;
  end if;
  for l in
    select * from public.pelham_bill_lines where bill_id = p_bill and kind = 'tee_player' and active
  loop
    select t.doc into v_doc from public.pelham_tee_bookings t where t.id = l.booking_id;
    v_player := public.pelham_pos_find_player(v_doc, l.player_id);
    if v_player is null or coalesce((v_player->>'cancelled')::boolean, false)
       or coalesce((v_player->>'paid')::boolean, false) then
      continue;
    end if;
    v_price := public.pelham_pos_tee_price(v_doc, v_player);
    update public.pelham_bill_lines
       set unit_price = v_price,
           line_total = v_price * quantity - least(discount, v_price * quantity),
           name = public.pelham_pos_tee_line_name(v_doc, v_player),
           tee_date = (v_doc->>'date')::date,
           tee_time = v_doc->>'time'
     where id = l.id;
  end loop;

  select coalesce(sum(line_total), 0) into v_subtotal
    from public.pelham_bill_lines where bill_id = p_bill and active;
  select b.discount into v_discount from public.pelham_bills b where b.id = p_bill;
  v_discount := least(coalesce(v_discount, 0), v_subtotal);
  v_taxable := v_subtotal - v_discount;

  update public.pelham_bills
     set subtotal = v_subtotal,
         discount = v_discount,
         tax = public.pelham_pos_tax(v_taxable),
         total = v_taxable + public.pelham_pos_tax(v_taxable)
   where id = p_bill;
end;
$$;

