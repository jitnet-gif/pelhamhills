-- 아직 안 나간 사람을 멈춘다. 이미 나간 문자·전화는 되돌릴 수 없다.
create or replace function public.pelham_marketing_campaign_cancel(p_id bigint)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_marketing_viewer();
  update public.pelham_marketing_sends s set status = 'cancelled', updated_at = now()
   where s.campaign_id = p_id and s.status = 'queued';
  update public.pelham_marketing_campaigns c
     set status = 'cancelled', finished_at = coalesce(c.finished_at, now())
   where c.id = p_id and c.status in ('ready', 'sending');
  return public.pelham_marketing_campaign(p_id);
end;
$$;

-- ===== 백엔드(서비스 키) 전용 ===============================================

-- 다음에 보낼 사람들을 집는다. 집는 순간 수신거부를 다시 본다(만든 뒤에 STOP 한 사람).
create or replace function public.pelham_marketing_claim(p_campaign bigint, p_limit integer)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_channel text;
  v_status text;
  v_sends jsonb;
begin
  select c.channel, c.status into v_channel, v_status
    from public.pelham_marketing_campaigns c where c.id = p_campaign for update;
  if v_channel is null then
    perform public.pelham_fail('404', 'No such campaign.');
  end if;
  if v_status = 'cancelled' then
    return jsonb_build_object('channel', v_channel, 'status', v_status, 'sends', '[]'::jsonb);
  end if;
  update public.pelham_marketing_campaigns c
     set status = 'sending', started_at = coalesce(c.started_at, now())
   where c.id = p_campaign and c.status = 'ready';

  update public.pelham_marketing_sends s
     set status = 'skipped', error = 'opted out', updated_at = now()
   where s.campaign_id = p_campaign and s.status = 'queued'
     and exists (select 1 from public.pelham_marketing_optouts o where o.phone = s.phone and o.channel = v_channel);

  -- 데이터를 바꾸는 WITH 는 맨 바깥에만 올 수 있어 결과를 변수로 받는다.
  with picked as (
    update public.pelham_marketing_sends s
       set status = 'sending', updated_at = now()
     where s.id in (select x.id from public.pelham_marketing_sends x
                     where x.campaign_id = p_campaign and x.status = 'queued'
                     order by x.id limit greatest(coalesce(p_limit, 1), 1)
                     for update skip locked)
    returning s.id, s.name, s.phone
  )
  select jsonb_agg(jsonb_build_object('id', picked.id, 'name', picked.name, 'phone', picked.phone) order by picked.id)
    into v_sends
    from picked;

  return jsonb_build_object('channel', v_channel, 'status', 'sending', 'sends', coalesce(v_sends, '[]'::jsonb));
end;
$$;

-- p: {id, status, provider_ref?, error?}
create or replace function public.pelham_marketing_send_result(p jsonb)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  update public.pelham_marketing_sends s
     set status = p->>'status',
         provider_ref = coalesce(p->>'provider_ref', s.provider_ref),
         error = left(p->>'error', 300),
         updated_at = now()
   where s.id = (p->>'id')::bigint
$$;

-- Twilio 전달 상태 콜백. 이미 끝난 상태(delivered/failed)는 뒤로 돌리지 않는다.
create or replace function public.pelham_marketing_status_by_ref(p_ref text, p_status text, p_error text)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  update public.pelham_marketing_sends s
     set status = case when p_status = 'delivered' then 'delivered'
                       when p_status in ('failed', 'undelivered') then 'failed'
                       else s.status end,
         error = coalesce(left(p_error, 300), s.error),
         updated_at = now()
   where s.provider_ref = p_ref and s.status in ('sent', 'sending')
$$;

-- 보낼 사람이 남지 않았으면 캠페인을 닫는다. 다 닫혔으면 true.
create or replace function public.pelham_marketing_finish(p_campaign bigint)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  if exists (select 1 from public.pelham_marketing_sends s
              where s.campaign_id = p_campaign and s.status in ('queued', 'sending')) then
    return false;
  end if;
  update public.pelham_marketing_campaigns c
     set status = 'sent', finished_at = now()
   where c.id = p_campaign and c.status = 'sending';
  return true;
end;
$$;

-- 서버 재시작으로 'sending' 에 걸린 줄을 다시 줄 세운다(백엔드가 보내기 시작할 때 부른다).
create or replace function public.pelham_marketing_requeue_stuck(p_campaign bigint)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  update public.pelham_marketing_sends s
     set status = 'queued', updated_at = now()
   where s.campaign_id = p_campaign and s.status = 'sending' and s.provider_ref is null
     and s.updated_at < now() - interval '5 minutes'
$$;

-- STOP 답장·전화 거절. 번호 꼴은 아무거나.
create or replace function public.pelham_marketing_optout_record(p_phone text, p_channel text, p_source text)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  insert into public.pelham_marketing_optouts (phone, channel, source)
  select public.pelham_marketing_phone(p_phone), p_channel, coalesce(p_source, 'reply')
   where public.pelham_marketing_phone(p_phone) is not null and p_channel in ('sms', 'call')
  on conflict do nothing
$$;

-- START 답장 — 문자 수신거부만 푼다(전화 동의는 따로).
create or replace function public.pelham_marketing_optin_record(p_phone text)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  delete from public.pelham_marketing_optouts o
   where o.phone = public.pelham_marketing_phone(p_phone) and o.channel = 'sms'
$$;

