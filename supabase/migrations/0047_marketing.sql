-- 고객 마케팅(`/marketing`) — 문자(Twilio)·AI 전화(ElevenLabs) 프로모션. 정해진 계정만 연다.
--
-- 왜(2026-10-20): 클럽이 고객 명부로 문자·전화 프로모션을 보내는 화면을 요청했다. 손님 전화번호를
-- 대량으로 다루므로 매니저와 Emmeline 만 본다. 현금 리포트(0046)처럼 **서버**가 막는다 —
-- 아래 함수는 명단(`pelham_marketing_viewers`) 밖 계정에 PT403 을 낸다.
--
-- 명단은 SQL editor 에서 바꾼다(화면이 없다). Supabase Auth 의 이메일로 적는다:
--   insert into public.pelham_marketing_viewers (email) values ('manager@example.com') on conflict do nothing;
--   delete from public.pelham_marketing_viewers where email = 'manager@example.com';
--   select * from public.pelham_marketing_viewers;
-- 명단에 있어도 직원(0004 의 pelham_is_staff)이어야 한다.
--
-- 누구에게 보낼 수 있나(캐나다 CASL·CRTC 를 따라 서버가 고른다):
--   문자  전화번호가 있고, 문자 수신거부가 아니고,
--         동의 표시(sms_ok)가 true 이거나 — 표시가 없으면 회원이거나 라운드 기록이 있는 손님(기존 거래 관계).
--         sms_ok = false 는 언제나 뺀다. 모든 문자 끝에 "Reply STOP to opt out" 이 붙는다(백엔드).
--   전화  AI 음성 발신은 자동 전화라 **명시적 동의(call_ok = true)** 가 있는 손님만. 전화 수신거부도 뺀다.
--   같은 번호를 쓰는 부부는 캠페인당 한 번만 보낸다.
-- 보내는 시각 제한(평일 9:00–21:30, 주말 10:00–18:00)은 백엔드(`backend/api/routes/marketing.py`)가 막는다.
--
-- 흐름: 화면이 캠페인을 만들면(받는 사람 명단을 그 순간 고정) 백엔드 `/marketing/campaigns/{id}/send` 가
-- 서비스 키로 `pelham_marketing_claim` → 한 명씩 보내고 → `pelham_marketing_send_result` 로 적는다.
-- 손님이 STOP 으로 답하면 `/sms/inbound` 가 `pelham_marketing_optout_record` 로 남긴다.
--
-- 전제: 0001, 0004, 0046(아니어도 됨). 실행: SQL editor 에 이 파일 전체를 붙여 한 번. 다시 실행해도 안전하다.

do $$
begin
  if to_regprocedure('public.pelham_require_staff()') is null then
    raise exception '0047 needs 0004 first (pelham_require_staff is missing).';
  end if;
  if to_regclass('public.pelham_customers') is null then
    raise exception '0047 needs 0001 first (pelham_customers is missing).';
  end if;
end;
$$;

