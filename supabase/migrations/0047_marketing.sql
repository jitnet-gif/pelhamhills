-- 손님마다 동의 표시. null = 표시 없음(문자는 기존 거래 관계로 판단, 전화는 안 됨).
create table if not exists public.pelham_marketing_prefs (
  customer_ref  text primary key references public.pelham_customers (customer_ref) on delete cascade,
  sms_ok        boolean,
  call_ok       boolean,
  note          text,
  updated_by    text,
  updated_at    timestamptz not null default now()
);

-- 번호(10자리)마다 수신거부. STOP 답장, 전화에서 "그만 걸어라", 직원이 손으로.
create table if not exists public.pelham_marketing_optouts (
  phone       text not null check (phone ~ '^\d{10}$'),
  channel     text not null check (channel in ('sms', 'call')),
  source      text not null default 'staff',
  created_at  timestamptz not null default now(),
  primary key (phone, channel)
);

create table if not exists public.pelham_marketing_campaigns (
  id           bigint generated by default as identity primary key,
  channel      text not null check (channel in ('sms', 'call')),
  name         text not null check (btrim(name) <> ''),
  message      text not null check (btrim(message) <> ''),
  audience     jsonb not null default '{}'::jsonb,
  status       text not null default 'ready' check (status in ('ready', 'sending', 'sent', 'cancelled')),
  created_by   text,
  created_at   timestamptz not null default now(),
  started_at   timestamptz,
  finished_at  timestamptz
);

create table if not exists public.pelham_marketing_sends (
  id            bigint generated by default as identity primary key,
  campaign_id   bigint not null references public.pelham_marketing_campaigns (id) on delete cascade,
  customer_ref  text,
  name          text,
  phone         text not null,
  status        text not null default 'queued'
                check (status in ('queued', 'sending', 'sent', 'delivered', 'failed', 'skipped', 'cancelled')),
  provider_ref  text,
  error         text,
  updated_at    timestamptz not null default now(),
  unique (campaign_id, phone)
);

create index if not exists pelham_marketing_sends_queue_idx
  on public.pelham_marketing_sends (campaign_id, id) where status = 'queued';
create index if not exists pelham_marketing_sends_ref_idx
  on public.pelham_marketing_sends (provider_ref) where provider_ref is not null;

alter table public.pelham_marketing_viewers enable row level security;
alter table public.pelham_marketing_prefs enable row level security;
