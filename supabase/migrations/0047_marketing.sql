-- 아무 꼴의 전화번호 → 10자리. 안 되면 null.
create or replace function public.pelham_marketing_phone(p_raw text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when d ~ '^\d{10}$' then d
    when d ~ '^1\d{10}$' then substr(d, 2)
    else null
  end
  from (select regexp_replace(coalesce(p_raw, ''), '\D', '', 'g') as d) x
$$;

-- ===== 받는 사람 =========================================================
-- p: {channel: sms|call, segment: all|members|non_members|regulars|new, min_rounds, search}
-- 고객 한 줄마다 보낼 수 있는지(ok)와 못 보내는 까닭(reason)을 붙인다.

create or replace function public.pelham_marketing_candidates(p jsonb)
returns table (customer_ref text, name text, phone text, is_member boolean, rounds integer,
               sms_ok boolean, call_ok boolean, ok boolean, reason text)
language sql
stable
security definer
set search_path = ''
as $$
  with args as (
    select case when p->>'channel' = 'call' then 'call' else 'sms' end as channel,
           coalesce(nullif(p->>'segment', ''), 'all') as segment,
           coalesce(nullif(p->>'min_rounds', '')::integer, 0) as min_rounds,
           lower(btrim(coalesce(p->>'search', ''))) as search
  ),
  base as (
    select c.customer_ref,
           coalesce(nullif(btrim(c.display_name), ''), btrim(concat_ws(' ', c.first_name, c.last_name))) as name,
           public.pelham_marketing_phone(c.phone) as phone,
           c.is_member,
           c.rounds_booked_played as rounds,
           c.user_created_on,
           pr.sms_ok,
           pr.call_ok
      from public.pelham_customers c
      left join public.pelham_marketing_prefs pr on pr.customer_ref = c.customer_ref
  )
  select b.customer_ref, b.name, b.phone, b.is_member, b.rounds, b.sms_ok, b.call_ok,
         r.reason is null as ok, r.reason
    from base b
   cross join args a
   cross join lateral (
     select case
       when b.phone is null then 'no_phone'
       when exists (select 1 from public.pelham_marketing_optouts o
                     where o.phone = b.phone and o.channel = a.channel) then 'opted_out'
       when a.channel = 'call' and b.call_ok is distinct from true then 'no_consent'
       when a.channel = 'sms' and (b.sms_ok = false
                                   or (b.sms_ok is null and not b.is_member and b.rounds <= 0)) then 'no_consent'
       else null
     end as reason
   ) r
   where case a.segment
           when 'members' then b.is_member
           when 'non_members' then not b.is_member
           when 'regulars' then b.rounds >= 5
           when 'new' then b.user_created_on >= (current_date - 365)
           else true
         end
     and b.rounds >= a.min_rounds
     and (a.search = ''
          or lower(coalesce(b.name, '')) like '%' || a.search || '%'
          or coalesce(b.phone, '') like '%' || regexp_replace(a.search, '\D', '', 'g') || '%'
             and regexp_replace(a.search, '\D', '', 'g') <> '')
$$;

create or replace function public.pelham_marketing_audience(p jsonb)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_marketing_viewer();
  return (
    with c as (select * from public.pelham_marketing_candidates(coalesce(p, '{}'::jsonb)))
    select jsonb_build_object(
      'total', count(*),
      'eligible', count(*) filter (where c.ok),
      'phones', count(distinct c.phone) filter (where c.ok),
      'no_phone', count(*) filter (where c.reason = 'no_phone'),
      'opted_out', count(*) filter (where c.reason = 'opted_out'),
      'no_consent', count(*) filter (where c.reason = 'no_consent'),
      'customers', coalesce(jsonb_agg(jsonb_build_object(
          'customer_ref', c.customer_ref, 'name', c.name, 'phone', c.phone,
          'is_member', c.is_member, 'rounds', c.rounds,
          'sms_ok', c.sms_ok, 'call_ok', c.call_ok, 'ok', c.ok, 'reason', c.reason
        ) order by c.ok desc, c.rounds desc, lower(c.name)), '[]'::jsonb)
    )
    from c
  );
end;
$$;

-- ===== 동의·수신거부 =====================================================

-- p: {customer_ref, sms_ok?, call_ok?, note?}. 키를 빼면 그 값은 그대로, null 이면 표시를 지운다.
create or replace function public.pelham_marketing_prefs_set(p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_ref text := btrim(coalesce(p->>'customer_ref', ''));
  v_by text;
  v_row public.pelham_marketing_prefs;
begin
  perform public.pelham_require_marketing_viewer();
  if not exists (select 1 from public.pelham_customers c where c.customer_ref = v_ref) then
    perform public.pelham_fail('404', 'No such customer.');
  end if;
  select lower(u.email) into v_by from auth.users u where u.id = auth.uid();

  insert into public.pelham_marketing_prefs as t (customer_ref, sms_ok, call_ok, note, updated_by)
  values (v_ref, (p->>'sms_ok')::boolean, (p->>'call_ok')::boolean, nullif(btrim(p->>'note'), ''), v_by)
  on conflict (customer_ref) do update
    set sms_ok = case when p ? 'sms_ok' then (p->>'sms_ok')::boolean else t.sms_ok end,
        call_ok = case when p ? 'call_ok' then (p->>'call_ok')::boolean else t.call_ok end,
        note = case when p ? 'note' then nullif(btrim(p->>'note'), '') else t.note end,
        updated_by = v_by,
        updated_at = now()
  returning * into v_row;
  return to_jsonb(v_row);
end;
$$;

-- p: {phone, channel: sms|call, opted_out: bool}
create or replace function public.pelham_marketing_optout_set(p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_phone text := public.pelham_marketing_phone(p->>'phone');
  v_channel text := p->>'channel';
begin
  perform public.pelham_require_marketing_viewer();
  if v_phone is null then
    perform public.pelham_fail('422', 'Enter a 10-digit phone number.');
  end if;
  if v_channel not in ('sms', 'call') then
    perform public.pelham_fail('422', 'channel must be sms or call.');
  end if;
  if coalesce((p->>'opted_out')::boolean, true) then
    insert into public.pelham_marketing_optouts (phone, channel, source)
    values (v_phone, v_channel, 'staff') on conflict do nothing;
  else
    delete from public.pelham_marketing_optouts o where o.phone = v_phone and o.channel = v_channel;
  end if;
  return jsonb_build_object('phone', v_phone, 'channel', v_channel,
                            'opted_out', coalesce((p->>'opted_out')::boolean, true));
end;
$$;

create or replace function public.pelham_marketing_optouts()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_marketing_viewer();
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'phone', o.phone, 'channel', o.channel, 'source', o.source, 'created_at', o.created_at,
             'name', (select coalesce(nullif(btrim(c.display_name), ''), btrim(concat_ws(' ', c.first_name, c.last_name)))
