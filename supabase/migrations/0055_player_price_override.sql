-- ===== 직원 함수: 한 선수의 그린피 ==========================================

create or replace function public.pelham_staff_player_green_fee(p_id text, p_player text, p_fee numeric, p_reason text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_now text := public.pelham_iso(now());
  v_doc jsonb;
  v_player jsonb;
  v_standard numeric;
  v_fee numeric := round(p_fee, 2);
  v_reason text := btrim(coalesce(p_reason, ''));
  v_live public.pelham_tee_price_overrides%rowtype;
  v_manager_id bigint;
  v_manager text;
  v_msg text;
begin
  perform public.pelham_require_staff();

  -- 0004 의 player_patch 와 같은 잠금: 티 타임 잠금을 잡고 doc 을 다시 읽는다.
  select t.doc into v_doc from public.pelham_tee_bookings t where t.id = p_id;
  if v_doc is null then
    perform public.pelham_fail('404', 'Booking not found');
  end if;
  perform public.pelham_tee_lock((v_doc->>'date')::date, v_doc->>'time');
  select t.doc into v_doc from public.pelham_tee_bookings t where t.id = p_id;
  if v_doc is null then
    perform public.pelham_fail('404', 'Booking not found');
  end if;

  select e.value into v_player
    from jsonb_array_elements(coalesce(v_doc->'players', '[]'::jsonb)) as e(value)
   where e.value->>'id' = p_player;
  if v_player is null then
    perform public.pelham_fail('404', 'Player not found');
  end if;
  if coalesce((v_player->>'paid')::boolean, false) then
    perform public.pelham_fail('409', 'Paid — mark unpaid to change the green fee.');
  end if;
  if coalesce((v_player->>'cancelled')::boolean, false) then
    perform public.pelham_fail('409', 'This player is cancelled.');
  end if;
  if v_fee is not null and v_fee < 0 then
    perform public.pelham_fail('422', 'Green fee cannot be negative.');
  end if;

  v_standard := public.pelham_tee_standard_green_fee(v_doc, v_player);
  select o.* into v_live from public.pelham_tee_price_overrides o
   where o.booking_id = p_id and o.player_id = p_player and o.cleared_at is null;

  -- 정상가로 돌아가기: 정정을 지운다. PIN 은 필요 없다.
  if v_fee is null or public.pelham_same_money(v_fee, v_standard) then
    if v_live.id is null then
      return v_doc;
    end if;
    update public.pelham_tee_price_overrides
       set cleared_at = now(), cleared_by = auth.uid()
     where id = v_live.id;
    v_msg := format('Green fee for %s back to the rate plan ($%s).',
                    v_player->>'name', to_char(v_standard, 'FM9999999990.00'));
  else
    if v_live.id is not null and public.pelham_same_money(v_live.green_fee, v_fee) and v_reason in ('', v_live.reason) then
      return v_doc;
    end if;
    if v_reason = '' then
      perform public.pelham_fail('422', 'Give a reason for the price change — it goes on the report.');
    end if;
    perform public.pelham_require_manager('price', coalesce(p_id, ''), format('changing %s''s green fee', v_player->>'name'));

    select a.manager_id, m.name into v_manager_id, v_manager
      from public.pelham_manager_approvals a
      left join public.pelham_managers m on m.id = a.manager_id
     where a.ok and a.requested_by is not distinct from auth.uid()
       and a.action = 'price' and a.ref = p_id
     order by a.created_at desc
     limit 1;

    if v_live.id is not null then
      update public.pelham_tee_price_overrides
         set cleared_at = now(), cleared_by = auth.uid()
       where id = v_live.id;
    end if;
    insert into public.pelham_tee_price_overrides
      (booking_id, player_id, green_fee, standard_fee, reason, manager_id, manager_name, requested_by)
    values (p_id, p_player, v_fee, v_standard, v_reason, v_manager_id, v_manager, auth.uid());

    v_msg := format('Green fee for %s set to $%s (rate plan $%s) — approved by %s: %s',
                    v_player->>'name', to_char(v_fee, 'FM9999999990.00'), to_char(v_standard, 'FM9999999990.00'),
                    coalesce(v_manager, 'a manager'), v_reason);
  end if;

  -- 트리거가 장부를 읽어 greenFee·priceOverride 를 다시 붙인다.
  v_doc := public.pelham_tee_audit(v_doc, v_msg, v_now);
  perform public.pelham_tee_save(v_doc);
  select t.doc into v_doc from public.pelham_tee_bookings t where t.id = p_id;
  return v_doc;
end;
$$;

-- ===== 0024 게이트: 저장된 doc 을 돌려준다 ====================================
-- player_patch 는 0024, booking_patch 는 0036 그대로 + 마지막 줄. `_ungated` 는 트리거가 손대기 전의 doc 을 돌려주므로, 그대로면 선수 이름 한 글자만
-- 고쳐도 화면에서 greenFee(회원 $0 등)·priceOverride 가 새로 읽을 때까지 사라져 보였다.

create or replace function public.pelham_staff_player_patch(p_id text, p_player text, p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_doc jsonb;
begin
  perform public.pelham_require_staff();
  if p ? 'paid' and jsonb_typeof(p->'paid') = 'boolean' and not (p->>'paid')::boolean then
    perform public.pelham_require_manager('mark_unpaid', coalesce(p_id, ''), 'clearing this payment');
  end if;
  -- 카트 요금을 손으로 바꿀 때만. 같은 금액을 다시 보내는 것은 통과시킨다.
  if p ? 'cartFee' and jsonb_typeof(p->'cartFee') = 'number' and exists (
       select 1 from public.pelham_tee_bookings t,
                     jsonb_array_elements(coalesce(t.doc->'players', '[]'::jsonb)) as pl(value)
        where t.id = p_id and pl.value->>'id' = p_player
          and round(coalesce((pl.value->>'cartFee')::numeric, 0), 2) <> round((p->>'cartFee')::numeric, 2)) then
    perform public.pelham_require_manager('price', coalesce(p_id, ''), 'changing the cart fee');
  end if;
  v_doc := public.pelham_staff_player_patch_ungated(p_id, p_player, p);
  return coalesce((select t.doc from public.pelham_tee_bookings t where t.id = p_id), v_doc);
end;
$$;

create or replace function public.pelham_staff_booking_patch(p_id text, p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_doc jsonb;
  v_new_holes integer;
begin
  perform public.pelham_require_staff();
  -- 그린피(예약 하나에 한 금액)를 바꿀 때만. 날짜·시간·홀·메모 같은 다른 수정은 그대로 둔다.
  if p ? 'rate' and jsonb_typeof(p->'rate') = 'number' and exists (
       select 1 from public.pelham_tee_bookings t
        where t.id = p_id
          and round(coalesce((t.doc->>'rate')::numeric, 0), 2) <> round((p->>'rate')::numeric, 2)) then
    perform public.pelham_require_manager('price', coalesce(p_id, ''), 'changing the green fee');
  end if;

  -- 홀 수가 바뀌면 그린피를 새 홀 수의 요금표 값으로. 잘못된 holes 값은 _ungated 가 422 로 거른다.
  if not (p ? 'rate' and jsonb_typeof(p->'rate') = 'number') and coalesce(p->>'holes', '') in ('9', '18') then
    select t.doc into v_doc from public.pelham_tee_bookings t where t.id = p_id;
    if v_doc is not null then
      v_new_holes := (p->>'holes')::integer;
      if v_new_holes <> coalesce((v_doc->>'holes')::integer, 18)
         and not exists (
           select 1 from jsonb_array_elements(coalesce(v_doc->'players', '[]'::jsonb)) pl
            where coalesce((pl.value->>'paid')::boolean, false)) then
        p := p || jsonb_build_object('rate', public.pelham_tee_rate_for((v_doc->>'date')::date, v_new_holes));
      end if;
    end if;
  end if;

  v_doc := public.pelham_staff_booking_patch_ungated(p_id, p);
  return coalesce((select t.doc from public.pelham_tee_bookings t where t.id = p_id), v_doc);
end;
$$;

comment on function public.pelham_staff_player_patch(text, text, jsonb) is 'pelham manager gate';
comment on function public.pelham_staff_booking_patch(text, jsonb) is 'pelham manager gate';

-- ===== 리포트: 정상가가 아닌 줄 =============================================

create or replace function public.pelham_staff_price_review(p_from date, p_to date)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_staff();
  if p_from is null or p_to is null or p_to < p_from then
    perform public.pelham_fail('422', 'Give a date range.');
  end if;
  if p_to - p_from > 62 then
    perform public.pelham_fail('422', 'Pick 62 days or fewer.');
  end if;

  return coalesce((
    with lines as (
      select t.id as booking_id,
             t.booking_date as play_date,
             coalesce(t.doc->>'time', '') as tee_time,
             public.pelham_tee_minutes(t.doc->>'time') as minutes,
             coalesce(t.doc->>'title', '') as title,
             coalesce(t.doc->>'confirmationCode', '') as code,
             case when coalesce(nullif(t.doc->>'holes', '')::integer, 18) = 9 then 9 else 18 end as holes,
             pl.value as player,
             public.pelham_tee_standard_green_fee(t.doc, pl.value) as green_standard,
             round(coalesce(case when jsonb_typeof(pl.value->'greenFee') = 'number'
                                 then (pl.value->>'greenFee')::numeric end,
                            (t.doc->>'rate')::numeric, 0), 2) as green_charged,
             case when coalesce((pl.value->>'cart')::boolean, false)
                  then round(public.pelham_tee_cart_fee_on(pl.value->>'ratePlan',
                         case when coalesce(nullif(t.doc->>'holes', '')::integer, 18) = 9 then 9 else 18 end,
                         t.booking_date), 2)
                  else 0 end as cart_standard,
             case when coalesce((pl.value->>'cart')::boolean, false)
                  then round(coalesce((pl.value->>'cartFee')::numeric, 0), 2) else 0 end as cart_charged
        from public.pelham_tee_bookings t
        cross join lateral jsonb_array_elements(
          case when jsonb_typeof(t.doc->'players') = 'array' then t.doc->'players' else '[]'::jsonb end) as pl(value)
       where t.booking_date between p_from and p_to
         and coalesce(t.status, '') not in ('cancelled', 'blocked')
         and not coalesce((pl.value->>'cancelled')::boolean, false)
    ),
    flagged as (
      select l.*,
             o.manager_name as ovr_manager, o.reason as ovr_reason, o.created_at as ovr_at,
             ap.manager_name as gate_manager, ap.created_at as gate_at
        from lines l
        left join public.pelham_tee_price_overrides o
          on o.booking_id = l.booking_id and o.player_id = l.player->>'id' and o.cleared_at is null
        left join lateral (
          select m.name as manager_name, a.created_at
            from public.pelham_manager_approvals a
            left join public.pelham_managers m on m.id = a.manager_id
           where a.ok and a.action = 'price' and a.ref = l.booking_id
           order by a.created_at desc
           limit 1
        ) ap on true
       where not public.pelham_same_money(l.green_standard, l.green_charged)
          or not public.pelham_same_money(l.cart_standard, l.cart_charged)
    )
    select jsonb_agg(jsonb_build_object(
             'bookingId', f.booking_id,
             'date', f.play_date,
             'time', f.tee_time,
             'title', f.title,
             'code', f.code,
             'holes', f.holes,
             'playerId', f.player->>'id',
             'player', coalesce(nullif(btrim(f.player->>'name'), ''), 'Guest'),
             'ratePlan', coalesce(f.player->>'ratePlan', ''),
             'paid', coalesce((f.player->>'paid')::boolean, false),
             'greenStandard', f.green_standard,
             'greenCharged', f.green_charged,
             'cartStandard', f.cart_standard,
             'cartCharged', f.cart_charged,
             'difference', round((f.green_charged + f.cart_charged) - (f.green_standard + f.cart_standard), 2),
             'kind', case when f.ovr_reason is not null then 'player'
                          when not public.pelham_same_money(f.green_standard, f.green_charged) then 'reservation'
                          else 'cart' end,
             'reason', coalesce(f.ovr_reason, ''),
             'manager', coalesce(f.ovr_manager, f.gate_manager, ''),
             'approvedAt', public.pelham_iso(coalesce(f.ovr_at, f.gate_at))
           ) order by f.play_date, f.minutes, f.booking_id, f.player->>'id')
      from flagged f
  ), '[]'::jsonb);
end;
$$;

