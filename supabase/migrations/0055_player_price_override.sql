-- 그룹·패밀리 예약에서도 선수 한 명의 그린피만 고칠 수 있게 한다. 매니저 PIN 이 있어야 하고,
-- 요금표와 다른 가격은 리포트(Daily close 의 Price review)에 검토 줄로 남는다.
--
-- 왜(2026-10-20): 선수 카드의 그린피 칸은 예약 단위 `rate`(0024 `price`)를 고쳤다. 그래서 네 명 그룹에서
-- 한 명만 할인해 주려 해도 네 명이 같이 바뀌었다. 그리고 정상가가 아닌 금액을 어디서도 다시 볼 수 없었다.
--
-- 바꾸는 것:
-- - `pelham_tee_price_overrides`: 선수별 정정 장부(예약·선수·금액·그때의 정상가·사유·승인한 매니저·시각).
--   한 선수에 살아 있는 줄은 하나. 되돌리면 `cleared_at` 이 찍히고 줄은 지우지 않는다.
-- - `pelham_staff_player_green_fee(id, player, fee, reason)`: 한 선수의 그린피를 정한다.
--   정상가와 다르면 사유가 있어야 하고 매니저 승인(0024 `price` · 예약 id)을 받는다.
--   fee 가 null 이거나 정상가와 같으면 정정을 지우고 요금제 값으로 돌아간다(PIN 없음 — 정상가로 돌아가는 것이다).
--   결제·취소된 선수는 바꿀 수 없다.
-- - 0045 트리거 `pelham_tee_bookings_time_rate`: 살아 있는 정정이 있는 선수는 요금제 대신 그 금액을 `greenFee` 로,
--   `priceOverride`({greenFee, standard, manager, reason, at})를 doc 에 붙인다. 장부가 진실이다 — 화면이 doc 에
--   `priceOverride` 를 심어 보내도 장부에 없으면 지운다. 0045 본문 그대로 + 이 부분만.
-- - `pelham_staff_price_review(from, to)`: 그 기간 플레이 날짜의 선수 중 그린피·카트 요금이 요금표와 다른 줄.
--   선수별 정정(사유·매니저), 예약 단위 그린피 변경(0024 승인 기록의 매니저), 카트 요금 변경을 모두 보여 준다.
--
-- - 0024 게이트 `pelham_staff_player_patch`·`pelham_staff_booking_patch`(0036 본문): 저장된 doc 을 돌려준다.
--
-- 전제: 0004, 0024, 0026, 0036, 0045. 실행: SQL editor 에 이 파일 전체를 붙여 한 번. 다시 실행해도 안전하다.
-- **0024·0036·0045 를 다시 실행하면 해당 함수가 이 파일 이전으로 돌아간다** — 그 뒤엔 이 파일을 다시 실행하면 된다.

do $$
begin
  if to_regprocedure('public.pelham_require_manager(text, text, text)') is null then
    raise exception '0055 needs 0024 first (pelham_require_manager is missing).';
  end if;
  if to_regprocedure('public.pelham_tee_plan_fee(text, date, integer, integer, numeric)') is null then
    raise exception '0055 needs 0045 first (pelham_tee_plan_fee is missing).';
  end if;
end;
$$;

