-- 모든 변경을 전·후 그대로 남기는 장부(Change log). 지워도 기록은 남고, 따로 정한 비밀번호로만 본다.
--
-- 왜(2026-10-20 클럽 요청): 예약 doc 의 History 는 예약 안에 들어 있어서 예약·선수·계산서를 지우면 기록도 같이
-- 사라졌다. 그리고 History 는 "무엇을 했다" 한 줄이라 바뀌기 전 값이 무엇이었는지 볼 수 없었다.
-- 이제 아래 테이블의 줄이 생기고·바뀌고·지워질 때마다 **바뀌기 전 줄과 바뀐 뒤 줄 전체**를 이 장부에 적는다.
-- 지운 줄도 "지우기 전" 이 그대로 남는다.
--
-- 누가 보나: 매니저와 Emmeline. 프로 샵 계정(0004 의 pelham_is_staff)으로 로그인한 뒤 **변경 기록 비밀번호**를
-- 한 번 더 넣어야 한다. 비밀번호는 매니저 PIN·로그인 비밀번호와 따로이고, 서버가 bcrypt 해시로만 갖는다.
-- 화면: Reports 의 "🔒 Change log" 탭(`/admin/reports?view=changes`, 현금 리포트 사이트 `/cash` 에도 같은 탭).
--
-- 바꾸는 것:
-- - `pelham_change_log`: 장부. 고칠 수도 지울 수도 없다(트리거가 막는다 — 직원 함수도, SQL editor 의 실수도).
-- - `pelham_change_log_capture()`: 테이블마다 붙는 AFTER 트리거. 누가(로그인 계정 이메일), 언제, 어느 테이블의 어느 줄을,
--   생성·수정·삭제했는지와 전·후 줄을 적는다. `updated_at` 만 바뀐 수정은 적지 않는다.
--   비밀 칸(`pin_hash` 같은 *_hash, password, token)은 장부에 넣지 않는다.
-- - `pelham_change_log_access`: 비밀번호 해시 한 줄. `pelham_change_log_password_set(text)` 로 정한다(SQL editor 에서만).
-- - `pelham_change_log_attempts`: 비밀번호 시도 기록(맞은 것·틀린 것). 15분 안에 5번 틀리면 15분 잠긴다.
-- - `pelham_staff_change_log(password, from, to, table, search, before_id)`: 장부 읽기. 비밀번호가 틀리면
--   오류가 아니라 `{ok:false}` 로 돌려준다 — 틀린 시도가 기록에 남아야 해서(0024 PIN 과 같다).
--
-- 지금 있는 테이블만 붙인다(없는 테이블은 건너뛴다). 나중에 만든 테이블은 이 파일을 다시 실행하면 붙는다.
-- 이 파일 이전의 변경은 장부에 없다 — 장부는 이 파일을 실행한 순간부터 쌓인다.
--
-- 전제: 0003, 0004, 0024(pgcrypto). 실행: SQL editor 에 이 파일 전체를 붙여 한 번. 다시 실행해도 안전하다(장부는 그대로).
-- 실행한 뒤 **비밀번호를 따로 한 번** 정한다(이 파일에는 비밀번호를 적지 않는다 — 저장소에 남기 때문):
--   select public.pelham_change_log_password_set('여기에 비밀번호');

do $$
begin
  if to_regprocedure('public.pelham_require_staff()') is null then
    raise exception '0057 needs 0004 first (pelham_require_staff is missing).';
  end if;
end;
$$;

create extension if not exists pgcrypto with schema extensions;

-- ===== 장부 ============================================================

create table if not exists public.pelham_change_log (
  id           bigint generated by default as identity primary key,
  at           timestamptz not null default now(),
  table_name   text not null,
  row_key      text,
  op           text not null check (op in ('insert', 'update', 'delete')),
  label        text,
  before_row   jsonb,
  after_row    jsonb,
  changed      text[],
  actor_id     uuid,
  actor_email  text
);
create index if not exists pelham_change_log_at_idx on public.pelham_change_log (at desc, id desc);
create index if not exists pelham_change_log_row_idx on public.pelham_change_log (table_name, row_key, at desc);

alter table public.pelham_change_log enable row level security;
revoke all on public.pelham_change_log from anon, authenticated;

-- 장부는 쌓이기만 한다.
create or replace function public.pelham_change_log_frozen()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'The change log cannot be edited or deleted.';
end;
$$;

drop trigger if exists pelham_change_log_frozen on public.pelham_change_log;
create trigger pelham_change_log_frozen
  before update or delete on public.pelham_change_log
  for each row execute function public.pelham_change_log_frozen();
drop trigger if exists pelham_change_log_frozen_truncate on public.pelham_change_log;
create trigger pelham_change_log_frozen_truncate
  before truncate on public.pelham_change_log
  for each statement execute function public.pelham_change_log_frozen();

-- ===== 비밀번호 ==========================================================

create table if not exists public.pelham_change_log_access (
  id             integer primary key default 1 check (id = 1),
  password_hash  text not null,
  updated_at     timestamptz not null default now()
);

create table if not exists public.pelham_change_log_attempts (
  id            bigint generated by default as identity primary key,
  ok            boolean not null,
  requested_by  uuid,
  email         text,
  created_at    timestamptz not null default now()
);
create index if not exists pelham_change_log_attempts_idx
  on public.pelham_change_log_attempts (requested_by, created_at desc);

alter table public.pelham_change_log_access enable row level security;
alter table public.pelham_change_log_attempts enable row level security;
revoke all on public.pelham_change_log_access from anon, authenticated;
revoke all on public.pelham_change_log_attempts from anon, authenticated;

-- SQL editor(postgres)에서만 부른다. 8자 이상.
create or replace function public.pelham_change_log_password_set(p_password text)
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  if p_password is null or length(p_password) < 8 then
    raise exception 'Use at least 8 characters.';
  end if;
  insert into public.pelham_change_log_access (id, password_hash, updated_at)
  values (1, extensions.crypt(p_password, extensions.gen_salt('bf')), now())
  on conflict (id) do update set password_hash = excluded.password_hash, updated_at = now();
  return 'Change log password set.';
end;
$$;

-- ===== 적기 ============================================================

-- 장부에 넣지 않을 칸을 뺀다.
create or replace function public.pelham_change_log_clean(p_row jsonb)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select case when p_row is null then null else
    coalesce((select jsonb_object_agg(e.key, e.value)
                from jsonb_each(p_row) e
               where e.key !~* '(_hash$|password|token|secret)'), '{}'::jsonb)
  end
$$;

-- 사람이 알아볼 이름: 예약은 제목·날짜·시각, 계산서는 영수증 번호, 그 밖엔 name/title/code/email.
create or replace function public.pelham_change_log_label(p_row jsonb)
returns text
language sql
immutable
set search_path = ''
as $$
  select nullif(btrim(concat_ws(' · ',
    coalesce(p_row->'doc'->>'title', p_row->>'receipt_no', p_row->>'code', p_row->>'name', p_row->>'title',
             nullif(btrim(concat_ws(' ', p_row->>'first_name', p_row->>'last_name')), ''),
             p_row->>'description', p_row->>'email', p_row->>'confirmation_code'),
    coalesce(p_row->'doc'->>'date', p_row->>'booking_date', p_row->>'business_date', p_row->>'date'),
    coalesce(p_row->'doc'->>'time', p_row->>'tee_time'))), '')
$$;

-- TG_ARGV[0] = 기본키 칸 이름(여러 개면 쉼표).
create or replace function public.pelham_change_log_capture()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_row jsonb;
  v_key text;
  v_changed text[];
  v_uid uuid := auth.uid();
  v_email text;
begin
  if tg_op in ('UPDATE', 'DELETE') then
    v_old := public.pelham_change_log_clean(to_jsonb(old));
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    v_new := public.pelham_change_log_clean(to_jsonb(new));
  end if;

  if tg_op = 'UPDATE' then
    select array_agg(k order by k) into v_changed
      from (select key as k from jsonb_each(v_old) union select key from jsonb_each(v_new)) keys
     where k <> 'updated_at' and (v_old->k) is distinct from (v_new->k);
    if v_changed is null then
      return null;
    end if;
  end if;

  v_row := coalesce(v_new, v_old);
  select string_agg(v_row->>btrim(c), ':') into v_key
    from unnest(string_to_array(coalesce(tg_argv[0], 'id'), ',')) c;

  if v_uid is not null then
    select u.email into v_email from auth.users u where u.id = v_uid;
  end if;

  insert into public.pelham_change_log
    (table_name, row_key, op, label, before_row, after_row, changed, actor_id, actor_email)
  values (tg_table_name, v_key, lower(tg_op), public.pelham_change_log_label(v_row),
          v_old, v_new, v_changed, v_uid, v_email);
  return null;
end;
$$;

-- 붙이기: 있는 테이블만. 기본키 칸은 카탈로그에서 읽는다.
do $$
declare
  v_table text;
  v_pk text;
begin
  foreach v_table in array array[
    'pelham_tee_bookings', 'pelham_tee_extras', 'pelham_tee_waitlist', 'pelham_tee_holidays',
    'pelham_tee_rate_bands', 'pelham_tee_rate_cards', 'pelham_tee_price_overrides',
    'pelham_bills', 'pelham_bill_lines', 'pelham_bill_payments', 'pelham_rain_checks',
    'pelham_register_closes', 'pelham_staff_closeouts', 'pelham_online_payments', 'pelham_terminal_transactions',
    'pelham_retail_products', 'pelham_retail_sales', 'pelham_retail_stock_moves',
    'pelham_customers', 'pelham_memberships', 'pelham_membership_payments',
    'pelham_sim_bays', 'pelham_sim_reservations', 'pelham_lost_items',
    'pelham_marketing_campaigns', 'pelham_marketing_optouts',
    'pelham_managers', 'pelham_cash_viewers', 'pelham_marketing_viewers'
  ] loop
    if to_regclass('public.' || v_table) is null then
      raise notice 'change log: % is not here, skipped', v_table;
      continue;
    end if;
    select string_agg(a.attname, ',' order by array_position(i.indkey, a.attnum)) into v_pk
      from pg_index i
      join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any (i.indkey)
     where i.indrelid = ('public.' || v_table)::regclass and i.indisprimary;
    execute format('drop trigger if exists pelham_change_log on public.%I', v_table);
    execute format('create trigger pelham_change_log after insert or update or delete on public.%I '
                   'for each row execute function public.pelham_change_log_capture(%L)',
                   v_table, coalesce(v_pk, 'id'));
  end loop;
end;
$$;

-- ===== 읽기 ============================================================

create or replace function public.pelham_staff_change_log(
  p_password text,
  p_from date,
  p_to date,
  p_table text default null,
  p_search text default null,
  p_before_id bigint default null
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_email text;
  v_hash text;
  v_fails integer;
  v_search text := nullif(btrim(coalesce(p_search, '')), '');
  v_limit integer := 200;
  v_rows jsonb;
begin
  perform public.pelham_require_staff();
  select u.email into v_email from auth.users u where u.id = v_uid;

  select a.password_hash into v_hash from public.pelham_change_log_access a where a.id = 1;
  if v_hash is null then
    return jsonb_build_object('ok', false, 'message', 'The change log password has not been set yet.');
  end if;

  select count(*) into v_fails from public.pelham_change_log_attempts t
   where not t.ok and t.requested_by is not distinct from v_uid and t.created_at > now() - interval '15 minutes';
  if v_fails >= 5 then
    return jsonb_build_object('ok', false, 'locked', true,
                              'message', 'Too many wrong passwords. Try again in 15 minutes.');
  end if;

  if p_password is null or extensions.crypt(p_password, v_hash) <> v_hash then
    insert into public.pelham_change_log_attempts (ok, requested_by, email) values (false, v_uid, v_email);
    return jsonb_build_object('ok', false, 'message', 'Wrong password.',
                              'triesLeft', greatest(0, 4 - v_fails));
  end if;

  -- 맞은 것은 열 때(첫 페이지)만 적는다 — 누가 언제 장부를 봤는지.
  if p_before_id is null then
    insert into public.pelham_change_log_attempts (ok, requested_by, email) values (true, v_uid, v_email);
  end if;

  if p_from is null or p_to is null or p_to < p_from then
    perform public.pelham_fail('422', 'Give a date range.');
  end if;
  if p_to - p_from > 92 then
    perform public.pelham_fail('422', 'Pick 92 days or fewer.');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id', c.id,
           'at', public.pelham_iso(c.at),
           'table', c.table_name,
           'rowKey', c.row_key,
           'op', c.op,
           'label', c.label,
           'before', c.before_row,
           'after', c.after_row,
           'changed', to_jsonb(c.changed),
           'actor', coalesce(c.actor_email, case when c.actor_id is null then 'system' else 'unknown' end)
         ) order by c.id desc), '[]'::jsonb)
    into v_rows
    from (select * from public.pelham_change_log c
           where c.at >= (p_from::timestamp at time zone 'America/Toronto')
             and c.at < ((p_to + 1)::timestamp at time zone 'America/Toronto')
             and (p_table is null or p_table = '' or c.table_name = p_table)
             and (p_before_id is null or c.id < p_before_id)
             and (v_search is null
                  or c.label ilike '%' || v_search || '%'
                  or c.row_key ilike '%' || v_search || '%'
                  or c.actor_email ilike '%' || v_search || '%'
                  or c.before_row::text ilike '%' || v_search || '%'
                  or c.after_row::text ilike '%' || v_search || '%')
           order by c.id desc
           limit v_limit + 1) c;

  -- 한 장에 200줄. 하나 더 읽어 다음 장이 있는지 안다(내림차순이라 덧 읽은 줄은 맨 끝).
  if jsonb_array_length(v_rows) > v_limit then
    return jsonb_build_object('ok', true, 'rows', v_rows - v_limit, 'more', true);
  end if;
  return jsonb_build_object('ok', true, 'rows', v_rows, 'more', false);
end;
$$;

