--   pelham_staff_ai_marketing_launches(report)                               그 보고서의 타일 상태
--                                                                             (캠페인 상태·보낸 수, 팝업 켜짐·기간).
-- 보고서처럼 지우지 않는다(트리거). 캠페인 취소·팝업 내리기는 각 시스템에서 한다.
