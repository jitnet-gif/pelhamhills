create table if not exists public.pelham_ai_marketing_launches (
  id bigint generated by default as identity primary key,
  report_id uuid not null references public.pelham_ai_marketing_reports (id),
  strategy_index integer not null check (strategy_index >= 0),
  channel text not null check (channel in ('sms', 'call', 'popup')),
  -- 캠페인 번호(0047) 또는 팝업 uuid(0060).
  ref text not null,
  created_at timestamptz not null default now(),
  created_by text not null default '',
  unique (channel, ref)
);

create index if not exists pelham_ai_marketing_launches_report on public.pelham_ai_marketing_launches (report_id);

alter table public.pelham_ai_marketing_launches enable row level security;
revoke all on public.pelham_ai_marketing_launches from public, anon, authenticated;

create or replace function public.pelham_ai_marketing_launches_keep()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'Launch records are kept for good and cannot be changed or deleted.';
end;
$$;

drop trigger if exists pelham_ai_marketing_launches_keep on public.pelham_ai_marketing_launches;
create trigger pelham_ai_marketing_launches_keep
  before update or delete or truncate on public.pelham_ai_marketing_launches
  for each statement execute function public.pelham_ai_marketing_launches_keep();

create or replace function public.pelham_staff_ai_marketing_launch_record(
  p_report uuid, p_strategy integer, p_channel text, p_ref text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_email text;
begin
  perform public.pelham_require_ai_marketing_viewer();
  if not exists (select 1 from public.pelham_ai_marketing_reports where id = p_report) then
    perform public.pelham_fail('404', 'That report is not in the archive.');
  end if;
  if p_channel not in ('sms', 'call', 'popup') or btrim(coalesce(p_ref, '')) = '' or p_strategy is null or p_strategy < 0 then
    perform public.pelham_fail('400', 'Unknown launch.');
  end if;
  select lower(u.email) into v_email from auth.users u where u.id = auth.uid();
  insert into public.pelham_ai_marketing_launches (report_id, strategy_index, channel, ref, created_by)
  values (p_report, p_strategy, p_channel, btrim(p_ref), coalesce(v_email, ''))
  on conflict (channel, ref) do nothing;
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.pelham_staff_ai_marketing_launches(p_report uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v jsonb;
begin
  perform public.pelham_require_ai_marketing_viewer();
  select coalesce(jsonb_agg(jsonb_build_object(
           'strategy', l.strategy_index, 'channel', l.channel, 'ref', l.ref,
           'created_at', public.pelham_iso(l.created_at), 'created_by', l.created_by,
           'campaign', case when l.channel in ('sms', 'call') and to_regclass('public.pelham_marketing_campaigns') is not null
                            then (select jsonb_build_object(
                                           'status', c.status, 'name', c.name,
                                           'recipients', (select count(*) from public.pelham_marketing_sends s where s.campaign_id = c.id),
                                           'sent', (select count(*) from public.pelham_marketing_sends s
                                                     where s.campaign_id = c.id and s.status in ('sent', 'delivered')),
                                           'failed', (select count(*) from public.pelham_marketing_sends s
                                                       where s.campaign_id = c.id and s.status = 'failed'))
                                    from public.pelham_marketing_campaigns c
                                   where l.ref ~ '^\d+$' and c.id = l.ref::bigint) end,
           'popup', case when l.channel = 'popup' and to_regclass('public.pelham_site_notices') is not null
                         then (select jsonb_build_object(
                                        'title', n.title, 'active', n.active,
                                        'starts_at', public.pelham_iso(n.starts_at), 'ends_at', public.pelham_iso(n.ends_at),
                                        'live', n.active and (n.starts_at is null or n.starts_at <= now())
                                                and (n.ends_at is null or n.ends_at > now()))
                                 from public.pelham_site_notices n
                                where l.ref ~ '^[0-9a-f-]{36}$' and n.id = l.ref::uuid) end)
         order by l.strategy_index, l.created_at), '[]'::jsonb)
    into v
    from public.pelham_ai_marketing_launches l
   where l.report_id = p_report;
  return v;
end;
$$;

