--   문자·AI 전화  pelham_marketing_campaign_create (0047). "ready" 로 만들어지고, 보내기는 Fly
--                 `/marketing/campaigns/{id}/send` (동의·수신거부·CRTC 시간 규칙 그대로).
--   팝업          pelham_staff_site_notice_save (0060). 숨긴 채(active=false) 만들거나 바로 켠다.
-- 이 파일은 그 둘의 번호를 전략에 이어 두는 표(`pelham_ai_marketing_launches`)와 상태를 읽는 함수만 둔다.
