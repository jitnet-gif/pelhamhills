-- 기프트카드: 매니저가 Gift Cards 화면에서 발행하고, 어느 계산서에서든 결제 수단 "Gift card" 로 잔액만큼 쓴다.
--
-- 왜(2026-10-26): 결제 수단 `gift_card` 는 0005 부터 있었지만 발행·잔액이 없어서, 직원이 "기프트카드로 받음" 이라고
-- 적기만 했다. 어떤 카드인지, 남은 돈이 얼마인지 아무도 몰랐다.
--
-- 흐름
--   1) Gift Cards 화면(매니저·계정 관리자, proshop@ 제외)에서 금액·받는 사람·사유를 넣고 발행한다. 서버가 코드
--      (`GIFT-` + 무작위 16진 10자)를 매기고, 화면이 그 코드를 Code 128 바코드로 담은 카드를 찍거나 문자로 보낸다.
--   2) 손님이 오면 계산서 결제에서 수단 "Gift card" 를 고르고 바코드를 쏜다(티 시트·계산대에서 바로 쏴도 된다).
--      잔액보다 적게 써도 되고, 남은 돈은 다음에 쓴다. 모자란 몫은 다른 수단으로 받는다.
--
-- 잔액 = 발행 금액 − 이 카드로 낸 결제 줄 중 계산서가 paid 인 것의 합. 따로 적어 두지 않는다 —
-- 그래서 카드로 낸 계산서를 환불하면(상태 refunded) 그 돈은 저절로 카드로 돌아온다.
--
-- 결제 함수(`pelham_staff_bill_pay`)는 바꾸지 않는다. 운영 DB 의 정의가 파일 글자 그대로가 아니다(0085·0087·0091).
-- 대신 `pelham_bill_payments` 의 BEFORE INSERT 트리거가 gift_card 줄을 본다: 화면은 카드 코드를 `auth_code` 에 담아
-- 보내고(결제 함수는 어느 수단이든 auth_code 를 그대로 넣는다), 트리거가 카드를 잠그고 상태·잔액을 확인한 뒤
-- `gift_card_id` 를 채운다. 트리거가 거절하면 결제 전체가 취소된다(같은 트랜잭션).
-- 코드 없이 들어오는 gift_card 결제는 거절한다 — 이 시스템 밖에서 판 옛 카드는 Gift Cards 화면에서 남은 금액으로
-- 한 장 발행해 바꿔 준다.
--
-- 만료일이 없다. 온타리오 소비자보호법은 기프트카드 만료를 금지한다.
--
-- 공유 프로젝트 규칙(0005 와 같다): 전부 `pelham_` 접두사, 테이블은 RLS 를 켜고 정책 없음,
-- 직원 함수는 첫 줄이 `pelham_require_staff()`. 오류는 PT403/PT404/PT409/PT422.
--
-- 전제: 0005, 0046(Reports 명단), 0074(계정 관리자). 실행: SQL editor 에 이 파일 전체를 붙여 한 번.
-- 다시 실행해도 안전하다.

-- ===== 먼저 확인 ======================================================
do $$
declare
  v_missing text[] := '{}';
  v_name text;
begin
  foreach v_name in array array['pelham_fail', 'pelham_iso', 'pelham_require_staff', 'pelham_pos_today',
                                 'pelham_is_cash_viewer', 'pelham_is_account_admin'] loop
    if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                    where n.nspname = 'public' and p.proname = v_name) then
      v_missing := v_missing || (v_name || '()');
    end if;
  end loop;
  if to_regclass('public.pelham_bill_payments') is null then
    v_missing := v_missing || 'pelham_bill_payments'::text;
  end if;
  if cardinality(v_missing) > 0 then
    raise exception '0120 needs 0005, 0046 and 0074 first. Missing: %', array_to_string(v_missing, ', ');
  end if;
end;
$$;

-- ===== 테이블 ==========================================================

create table if not exists public.pelham_gift_cards (
  id            bigint generated by default as identity primary key,
  -- 카드의 바코드 값. 무작위다 — 순번이면 옆 번호를 쳐서 남의 잔액을 쓸 수 있다.
  code          text not null unique check (code ~ '^GIFT-[0-9A-F]{10}$'),
  -- 발행 금액(센트). 잔액은 결제 줄에서 계산한다.
  amount        integer not null check (amount > 0 and amount <= 500000),
  -- sold = 돈을 받고 팔았다(선수금), complimentary = 무료(보상·경품·기부).
  kind          text not null check (kind in ('sold', 'complimentary')),
  status        text not null default 'active' check (status in ('active', 'void')),
  recipient     text,
  phone         text,
  email         text,
  note          text,
  issued_by     uuid,
  issued_email  text,
  issued_on     date not null,
  issued_at     timestamptz not null default now(),
  void_reason   text,
  voided_at     timestamptz,
  check ((status = 'void') = (voided_at is not null))
);

alter table public.pelham_gift_cards enable row level security;

-- 결제 줄: 어느 카드로 냈는가.
alter table public.pelham_bill_payments
  add column if not exists gift_card_id bigint references public.pelham_gift_cards (id);
alter table public.pelham_bill_payments drop constraint if exists pelham_bill_payments_gift_card_check;
alter table public.pelham_bill_payments add constraint pelham_bill_payments_gift_card_check
  check (gift_card_id is null or method = 'gift_card');
create index if not exists pelham_bill_payments_gift_card_idx on public.pelham_bill_payments (gift_card_id);

-- ===== 헬퍼 (실행 권한을 아무에게도 주지 않는다) ========================

-- 발행·무효는 매니저(Reports 명단)와 계정 관리자. proshop@ 는 매장 컴퓨터에서 여럿이 같이 쓰므로 뺀다(0102 와 같다).
create or replace function public.pelham_is_gift_card_manager()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.pelham_is_account_admin()
      or (public.pelham_is_cash_viewer()
          and not exists (select 1
                            from auth.users u
                           where u.id = auth.uid()
                             and lower(u.email) in ('proshop@pelhamhills.ca')))
$$;

create or replace function public.pelham_require_gift_card_manager()
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_staff();
  if not public.pelham_is_gift_card_manager() then
    perform public.pelham_fail('403', 'Only managers can issue or void gift cards.');
  end if;
end;
$$;

-- 이 카드로 쓴 돈(센트). 결제된 계산서만 — 환불된 계산서의 돈은 카드로 돌아와 있다.
-- `p_bill` 은 지금 결제 중인 계산서: 아직 open 이지만 같은 트랜잭션에서 먼저 넣은 줄도 센다.
create or replace function public.pelham_gc_used(p_card bigint, p_bill bigint default null)
returns integer
language sql
stable
set search_path = ''
as $$
  select coalesce(sum(p.amount), 0)::integer
    from public.pelham_bill_payments p
    join public.pelham_bills b on b.id = p.bill_id
   where p.gift_card_id = p_card
     and (b.status = 'paid' or b.id = p_bill)
$$;

create or replace function public.pelham_gc_json(g public.pelham_gift_cards)
returns jsonb
language sql
stable
set search_path = ''
as $$
  select jsonb_build_object(
    'id', g.id,
    'code', g.code,
    'amount', g.amount,
    'used', u.used,
    'balance', g.amount - u.used,
    'kind', g.kind,
    'status', g.status,
    'recipient', g.recipient,
    'phone', g.phone,
    'email', g.email,
    'note', g.note,
    'issued_email', g.issued_email,
    'issued_on', to_char(g.issued_on, 'YYYY-MM-DD'),
    'issued_at', public.pelham_iso(g.issued_at),
    'void_reason', g.void_reason,
    'voided_at', public.pelham_iso(g.voided_at),
    'uses', coalesce((
      select jsonb_agg(jsonb_build_object(
               'receipt_no', b.receipt_no,
               'amount', p.amount,
               'status', b.status,
               'paid_at', public.pelham_iso(b.paid_at)
             ) order by p.id)
        from public.pelham_bill_payments p
        join public.pelham_bills b on b.id = p.bill_id
       where p.gift_card_id = g.id and b.status in ('paid', 'refunded')
    ), '[]'::jsonb)
  )
  from (select public.pelham_gc_used(g.id) as used) u
$$;

-- ===== 결제 줄 트리거 ===================================================

-- gift_card 결제 줄: 코드(auth_code)로 카드를 잠그고 상태·잔액을 본다. 실패하면 결제 전체가 취소된다.
-- 잠금은 트랜잭션 끝까지 간다 — 두 계산대가 같은 카드로 동시에 결제하면 뒤의 것이 기다렸다가 줄어든 잔액을 본다.
create or replace function public.pelham_gc_on_payment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_code text;
  g public.pelham_gift_cards;
  v_balance integer;
begin
  if new.method <> 'gift_card' then
    return new;
  end if;
  v_code := upper(btrim(coalesce(new.auth_code, '')));
  if v_code = '' then
    perform public.pelham_fail('422', 'A gift card payment needs the card number. Scan the gift card.');
  end if;
  select * into g from public.pelham_gift_cards where code = v_code for update;
  if g.id is null then
    perform public.pelham_fail('404', format('No gift card %s', v_code));
  end if;
  if g.status <> 'active' then
    perform public.pelham_fail('409', format('Gift card %s was voided.', v_code));
  end if;
  if coalesce(new.tip, 0) > 0 then
    perform public.pelham_fail('422', 'Tips cannot be paid with a gift card.');
  end if;
  v_balance := g.amount - public.pelham_gc_used(g.id, new.bill_id);
  if new.amount > v_balance then
    perform public.pelham_fail('422', format('Gift card %s has %s left, not %s.', v_code,
                                             '$' || to_char(v_balance / 100.0, 'FM999,990.00'),
                                             '$' || to_char(new.amount / 100.0, 'FM999,990.00')));
  end if;
  new.gift_card_id := g.id;
  new.auth_code := v_code;
  new.entry := 'none';
  new.terminal := null;
  new.card_last4 := null;
  return new;
end;
$$;

drop trigger if exists pelham_gc_on_payment on public.pelham_bill_payments;
create trigger pelham_gc_on_payment
  before insert on public.pelham_bill_payments
  for each row execute function public.pelham_gc_on_payment();

