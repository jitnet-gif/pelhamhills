-- 코드로 찾기(결제 칸에서 카드를 쐈을 때). 직원 누구나. 실제 판정은 결제 때 트리거가 잠금 안에서 다시 한다.
create or replace function public.pelham_staff_gift_card(p_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  g public.pelham_gift_cards;
begin
  perform public.pelham_require_staff();
  select * into g from public.pelham_gift_cards where code = upper(btrim(coalesce(p_code, '')));
  if g.id is null then
    perform public.pelham_fail('404', format('No gift card %s', coalesce(p_code, '')));
  end if;
  return public.pelham_gc_json(g);
end;
$$;

-- 전부(새것부터). 매니저만.
create or replace function public.pelham_staff_gift_cards()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_gift_card_manager();
  return coalesce((
    select jsonb_agg(public.pelham_gc_json(g) order by g.issued_at desc, g.id desc)
      from public.pelham_gift_cards g
  ), '[]'::jsonb);
end;
$$;

-- p: {amount (센트), kind, recipient?, phone?, email?, note?}
create or replace function public.pelham_staff_gift_card_issue(p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_amount integer;
  v_kind text := coalesce(p->>'kind', '');
  v_code text;
  v_email text;
  g public.pelham_gift_cards;
begin
  perform public.pelham_require_gift_card_manager();
  p := coalesce(p, '{}'::jsonb);
  begin
    v_amount := (p->>'amount')::integer;
  exception when others then
    perform public.pelham_fail('422', 'amount must be whole cents.');
  end;
  if v_amount is null or v_amount <= 0 then
    perform public.pelham_fail('422', 'Enter an amount above $0.00.');
  end if;
  if v_amount > 500000 then
    perform public.pelham_fail('422', 'A gift card cannot be more than $5,000.00.');
  end if;
  if v_kind not in ('sold', 'complimentary') then
    perform public.pelham_fail('422', 'Choose Sold or Complimentary.');
  end if;
  if length(btrim(coalesce(p->>'note', ''))) = 0 then
    perform public.pelham_fail('422', 'Write why the card is issued (who paid and how, or what it is for).');
  end if;

  -- 코드: 무작위 10자(16진). 겹치면 다시 뽑는다.
  loop
    v_code := 'GIFT-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));
    exit when not exists (select 1 from public.pelham_gift_cards where code = v_code);
  end loop;
  select lower(u.email) into v_email from auth.users u where u.id = auth.uid();

  insert into public.pelham_gift_cards
    (code, amount, kind, recipient, phone, email, note, issued_by, issued_email, issued_on)
  values
    (v_code, v_amount, v_kind,
     nullif(btrim(coalesce(p->>'recipient', '')), ''),
     nullif(btrim(coalesce(p->>'phone', '')), ''),
     nullif(lower(btrim(coalesce(p->>'email', ''))), ''),
     btrim(p->>'note'), auth.uid(), v_email, public.pelham_pos_today())
  returning * into g;
  return public.pelham_gc_json(g);
end;
$$;

-- 무효. 사유는 필수. 남은 잔액이 없어진다(이미 쓴 결제는 그대로 남는다).
create or replace function public.pelham_staff_gift_card_void(p_code text, p_reason text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  g public.pelham_gift_cards;
begin
  perform public.pelham_require_gift_card_manager();
  if length(btrim(coalesce(p_reason, ''))) = 0 then
    perform public.pelham_fail('422', 'Give a reason for voiding the gift card.');
  end if;
  select * into g from public.pelham_gift_cards where code = upper(btrim(coalesce(p_code, ''))) for update;
  if g.id is null then
    perform public.pelham_fail('404', format('No gift card %s', coalesce(p_code, '')));
  end if;
  if g.status <> 'active' then
    perform public.pelham_fail('409', format('Gift card %s is already voided.', g.code));
  end if;
  update public.pelham_gift_cards
     set status = 'void', voided_at = now(), void_reason = btrim(p_reason)
   where id = g.id
  returning * into g;
  return public.pelham_gc_json(g);
end;
$$;

